// pacer — the shared test harness leaf (02 T3.1).
//
// Extracted from corpus.test.js so BOTH the corpus parity walk and the
// rt driver's parity test (T3.2) run identical harness steps and render
// through the SAME canonical golden formatter — one renderer, shared,
// never a duplicated formatter that can drift. The canonical format is
// defined in src/corpus_runner.zig's header (the native runner is the
// authority); regenerate goldens with `zig build corpus -- --update`.
// Zero behavior change: this is a pure move of parseHarness +
// renderCase; corpus.test.js imports them back from here.

const GENERATED_HEADER =
  '; pacer corpus golden — GENERATED by `zig build corpus -- --update`; do not hand-edit.\n';
const PACW_HEADER_LEN = 12;
const PACW_ENTRY_LEN = 20;

/**
 * Parse the constrained harness format (times.sjon): flat
 * `(target NAME :registry R :ncomp N)` forms — flat order IS the
 * target_id space, and must precede all script forms — then script
 * forms executed in document order: `(times "H16" …)`,
 * `(set-control :index N :value ["H8"×4])`, `(clear-control :index N)`,
 * `(set-bpm :bpm "H16")`, `(register-control :target-id N …)`. Comments
 * are `;` to end of line and never contain quotes; the native runner
 * parses the same file with real SJON and is the stricter check.
 */
export function parseHarness(src) {
  const stripped = src.replace(/;[^\n]*/g, '');
  const flat = [];
  const steps = [];
  let sawScript = false;
  for (const m of stripped.matchAll(/\(([a-z][a-z-]*)([^)]*)\)/g)) {
    const [, head, body] = m;
    if (head === 'target') {
      if (sawScript) throw new Error('harness: (target …) forms must precede all script forms');
      const name = body.match(/^\s*([^\s:)]+)/);
      if (!name) throw new Error('harness: (target …) needs a name');
      const target = { name: name[1], ncomp: 1, registry: 0 };
      for (const kv of body.matchAll(/:([a-z]+)\s+(\d+)/g)) {
        if (kv[1] === 'ncomp') target.ncomp = Number(kv[2]);
        else if (kv[1] === 'registry') target.registry = Number(kv[2]);
        else throw new Error(`harness: unknown target key :${kv[1]}`);
      }
      flat.push(target);
    } else if (head === 'times') {
      sawScript = true;
      for (const t of body.matchAll(/"([0-9A-Fa-f]{16})"/g))
        steps.push({ kind: 'eval', bits: BigInt(`0x${t[1]}`) });
    } else if (head === 'set-control') {
      sawScript = true;
      steps.push({
        kind: 'set-control',
        index: harnessInt(body, 'index'),
        bits: harnessLanes(body),
      });
    } else if (head === 'clear-control') {
      sawScript = true;
      steps.push({ kind: 'clear-control', index: harnessInt(body, 'index') });
    } else if (head === 'set-bpm') {
      sawScript = true;
      const b = body.match(/"([0-9A-Fa-f]{16})"/);
      if (!b) throw new Error('harness: (set-bpm …) needs a :bpm 16-hex string');
      steps.push({ kind: 'set-bpm', bits: BigInt(`0x${b[1]}`) });
    } else if (head === 'register-control') {
      sawScript = true;
      steps.push({
        kind: 'register-control',
        targetId: harnessInt(body, 'target-id'),
        registry: harnessInt(body, 'registry'),
        ncomp: harnessInt(body, 'ncomp'),
      });
    } else {
      throw new Error(`harness: unknown form (${head} …)`);
    }
  }
  // An empty target list is legal: a compose-mode score declares its own
  // targets with (target …) and compiles standalone (the join then comes
  // wholly from the score — see parseDeclaredTargets).
  if (steps.length === 0) throw new Error('harness: empty script');

  // Regroup the flat list for Pacer.load; non-decreasing registry
  // indices (enforced by the native runner) keep flatMap's order equal
  // to the file's flat order, so target_ids agree.
  const registries = [];
  for (const t of flat) {
    while (registries.length <= t.registry) registries.push([]);
    registries[t.registry].push({ name: t.name, ncomp: t.ncomp });
  }
  return { flat, registries, steps };
}

/** `:key N` as an integer, from a harness form body. */
function harnessInt(body, key) {
  const m = body.match(new RegExp(`:${key}\\s+(\\d+)`));
  if (!m) throw new Error(`harness: missing :${key}`);
  return Number(m[1]);
}

/** `:value ["H8" "H8" "H8" "H8"]` as four u32 f32-bit patterns. */
function harnessLanes(body) {
  const lanes = [...body.matchAll(/"([0-9A-Fa-f]{8})"/g)].map((x) => Number.parseInt(x[1], 16));
  if (lanes.length !== 4) throw new Error('harness: :value needs four 8-hex lanes');
  return lanes;
}

/**
 * The merged target-name join a `target_id` indexes: the host registries'
 * flat names, then any compose-mode `(target :name X …)` the score
 * declares that the host did NOT already provide — in document order.
 * Declared names ride in the score source (never on the wire), so the
 * native runner reads them from `result.targets` and this walk mirrors it
 * from the same source, keeping the two golden renderings byte-equal.
 * For a fully-hosted score (no declarations) this is just the flat names,
 * so every existing golden is untouched.
 */
function mergedTargetNames(doc, flat) {
  const names = flat.map((t) => t.name);
  // ONE left-to-right scan so a `(target …)` inside a comment or string is
  // consumed as that token, never mistaken for a declaration — mirroring
  // the SJON lexer the native side parses with. Alternation order encodes
  // lexer precedence: `#| … |#` block comment (non-nesting in SJON v0.1),
  // `; …` line comment, `"…"` string, then a REAL `(target …)` (the only
  // alternative with a capture group). matchAll advances past each match,
  // so a comment/string starting first swallows any `(target …)` within it.
  const token = /#\|[\s\S]*?\|#|;[^\n]*|"(?:[^"\\]|\\.)*"|\(target\b([^)]*)\)/g;
  for (const m of doc.matchAll(token)) {
    if (m[1] === undefined) continue; // a comment or string — not a declaration
    const nm = m[1].match(/:name\s+([^\s):]+)/);
    if (nm && !names.includes(nm[1])) names.push(nm[1]);
  }
  return names;
}

/** Uppercase fixed-width hex — Zig's `{X:0>w}`; accepts number or BigInt. */
const hex = (value, width) => value.toString(16).toUpperCase().padStart(width, '0');

const f64FromBits = (bits) => {
  const dv = new DataView(new ArrayBuffer(8));
  dv.setBigUint64(0, bits);
  return dv.getFloat64(0);
};
const f64Bits = (x) => {
  const dv = new DataView(new ArrayBuffer(8));
  dv.setFloat64(0, x);
  return dv.getBigUint64(0);
};
const f32FromBits = (bits) => {
  const dv = new DataView(new ArrayBuffer(4));
  dv.setUint32(0, bits);
  return dv.getFloat32(0);
};
const f32Bits = (x) => {
  const dv = new DataView(new ArrayBuffer(4));
  dv.setFloat32(0, x);
  return dv.getUint32(0);
};

/** Four f32 lanes as space-separated `"H8"` bit patterns (no brackets). */
const laneHex = (arr) => arr.map((x) => `"${hex(f32Bits(x), 8)}"`).join(' ');

function escapeMessage(msg) {
  let out = '';
  for (const ch of msg) {
    if (ch.codePointAt(0) < 0x20) throw new Error('control byte in diagnostic message');
    if (ch === '"' || ch === '\\') out += '\\';
    out += ch;
  }
  return out;
}

/** Render one eval's raw 'PACW' bytes as canonical `(write …)` lines. */
function renderWrites(bytes, names) {
  const dv = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  const count = dv.getUint32(8, true);
  let out = '';
  for (let i = 0; i < count; i++) {
    const off = PACW_HEADER_LEN + i * PACW_ENTRY_LEN;
    const targetId = dv.getUint16(off, true);
    const lanes = [];
    for (let c = 0; c < 4; c++) lanes.push(`"${hex(dv.getUint32(off + 4 + c * 4, true), 8)}"`);
    out += `\n  (write :target ${names[targetId]} :id ${targetId}`;
    out += ` :registry ${dv.getUint8(off + 2)} :ncomp ${dv.getUint8(off + 3)}`;
    out += ` :value [${lanes.join(' ')}])`;
  }
  return out;
}

/**
 * Render the `(meta …)` block from the DECODED `driver.meta` object —
 * the native runner renders the same text from the encoded 'PACM' blob,
 * so byte-parity gates both the encoder and this decoder.
 */
function renderMeta(meta, names) {
  const t = meta.transport;
  let out = `(meta :bpm "${hex(f64Bits(t.bpm), 16)}" :beats-per-bar ${t.beatsPerBar}`;
  if (t.dur !== null) out += ` :dur ${t.dur} :end ${t.end}`;
  for (const tr of meta.tracks) {
    out += `\n  (mtrack :id ${tr.targetId} :target ${names[tr.targetId]} :registry ${tr.registry}`;
    out += ` :ncomp ${tr.ncomp} :source ${tr.source} :span [${tr.span.start} ${tr.span.end}]`;
    for (const k of tr.keys) {
      out += `\n    (mkey :at ${k.at} :value [${laneHex(k.value)}] :span [${k.span.start} ${k.span.end}])`;
    }
    out += ')';
  }
  for (const c of meta.controls) {
    const rail = (r) => (r ? `[${laneHex(r)}]` : 'none');
    const targetName = c.targetId === null ? 'none' : names[c.targetId];
    out += `\n  (mcontrol :index ${c.index} :id ${c.id} :target ${targetName}`;
    out += ` :registry ${c.registry} :ncomp ${c.ncomp} :type ${c.type} :value [${laneHex(c.value)}]`;
    out += ` :min ${rail(c.min)} :max ${rail(c.max)} :value-span [${c.valueSpan.start} ${c.valueSpan.end}])`;
  }
  // The 'SCEN' section (post-controls TLV): named windows, name sliced
  // from source via nameSpan. The native runner walks the same section.
  for (const s of meta.scenes) {
    out += `\n  (mscene :name ${s.name} :at ${s.startTick} :dur ${s.durTicks}`;
    out += ` :name-span [${s.nameSpan.start} ${s.nameSpan.end}])`;
  }
  // The 'EASE' section (after 'SCEN'): the deduped program table, then a
  // flat per-key program-index list in key order. Present only when a
  // non-linear program exists — mirror of the native runner's walk.
  if (meta.easePrograms.length) {
    for (const prog of meta.easePrograms) {
      out += `\n  (mease :index ${prog.index}`;
      for (const st of prog.stages) {
        out += `\n    (mstage :t-end "${hex(f32Bits(st.tEnd), 8)}"`;
        out += ` :v-base "${hex(f32Bits(st.vBase), 8)}" :v-span "${hex(f32Bits(st.vSpan), 8)}"`;
        for (const op of st.ops) {
          const params = op.params.map((p) => `"${hex(f32Bits(p), 8)}"`).join(' ');
          out += `\n      (mop :code ${op.code} :params [${params}])`;
        }
        out += ')';
      }
      out += ')';
    }
    const refs = meta.tracks.flatMap((tr) => tr.keys.map((k) => k.easeRef));
    out += `\n  (measerefs [${refs.join(' ')}])`;
  }
  // The 'TMPO' section (after 'EASE'): tempo segments including segment
  // 0, ticks decimal, bpm as an f64 bit pattern — the native runner's
  // mirror. Empty (omitted on the wire) for a constant-tempo score.
  for (const seg of meta.tempoMap) {
    out += `\n  (mtempo :tick ${seg.tick} :bpm "${hex(f64Bits(seg.bpm), 16)}")`;
  }
  return `${out})\n`;
}

/**
 * Render one case through the canonical golden text: the GENERATED
 * header, the `(load …)` line and any `(diag …)` echoes, the `(meta …)`
 * block, then the harness steps in order — evals rendered from the
 * driver's raw bytes, script directives echoed with their acceptance.
 * The driver is passed IN (already loaded with the score + registries)
 * so the SAME renderer serves any driver with the `Pacer` call surface
 * — the corpus walk's text-path driver and, at T3.2, the playback
 * runtime's.
 *
 * @param {string} doc - the score source (also the declared-names join).
 * @param {ReturnType<typeof parseHarness>} harness
 * @param {import('../src/index.js').Pacer} driver
 * @returns {Promise<string>} the canonical golden text
 */
export async function renderCase(doc, harness, driver) {
  let out = GENERATED_HEADER;
  out += `(load :ok ${driver.ok})\n`;
  for (const d of driver.diagnostics) {
    out += `(diag :source ${d.source} :severity ${d.severity} :code ${d.code}`;
    out += ` :start ${d.start} :end ${d.end} :message "${escapeMessage(d.message)}")\n`;
  }
  if (!driver.ok) return out;

  // The join a target_id names: host flat names + compose-mode declared
  // names (from the score source), mirroring the native runner's
  // result.targets. For a fully-hosted score this is just the flat names.
  const names = mergedTargetNames(doc, harness.flat);

  // Meta reflects the document — render before any set-bpm nudge.
  out += renderMeta(driver.meta, names);

  for (const step of harness.steps) {
    if (step.kind === 'eval') {
      const head = `(eval :t "${hex(step.bits, 16)}"`;
      const bytes = driver.evalBytes(f64FromBits(step.bits));
      out +=
        bytes === null
          ? `${head} :out-of-range true)\n`
          : `${head}${renderWrites(bytes, names)})\n`;
    } else if (step.kind === 'set-control') {
      const ok = driver.setControl(step.index, step.bits.map(f32FromBits));
      const value = step.bits.map((b) => `"${hex(b, 8)}"`).join(' ');
      out += `(set-control :index ${step.index} :value [${value}] :ok ${ok})\n`;
    } else if (step.kind === 'clear-control') {
      out += `(clear-control :index ${step.index} :ok ${driver.clearControl(step.index)})\n`;
    } else if (step.kind === 'set-bpm') {
      const ok = driver.setBpm(f64FromBits(step.bits));
      out += `(set-bpm :bpm "${hex(step.bits, 16)}" :ok ${ok})\n`;
    } else if (step.kind === 'register-control') {
      const slot = driver.registerControl(harness.flat[step.targetId].name);
      out += `(register-control :target-id ${step.targetId} :registry ${step.registry}`;
      out += ` :ncomp ${step.ncomp} :slot ${slot === null ? 'none' : slot})\n`;
    }
  }
  return out;
}
