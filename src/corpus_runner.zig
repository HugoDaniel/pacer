//! Golden-corpus runner — the native half of pacer's determinism gate.
//!
//! Each `corpus/<case>/` directory holds:
//!
//!   - `doc.sjon`      — the score, byte-for-byte what a host loads;
//!   - `times.sjon`    — the harness: the flat target join plus eval
//!                       times as hex f64 bit patterns;
//!   - `expected.sjon` — GENERATED golden: load outcome + every write
//!                       buffer, floats as hex bit patterns.
//!
//! Harness format (hand-authored, parsed with real `sjon.parse`). The
//! `(target …)` forms come first — flat order IS the target_id space —
//! then script forms execute IN DOCUMENT ORDER:
//!
//!     (target circle-radius :registry 0)   ; flat order IS the target_id space
//!     (target tint :registry 0 :ncomp 3)   ; registries non-decreasing
//!     (target cutoff :registry 1)
//!     (times "0000000000000000" "3FE0000000000000")            ; one eval each
//!     (set-control :index 0 :value ["3F000000" "0" "0" "0"])   ; hold a value
//!     (clear-control :index 0)                                 ; release it
//!     (set-bpm :bpm "4059000000000000")                       ; live tempo nudge
//!     (register-control :target-id 2 :registry 1 :ncomp 1)     ; lift a slot
//!
//! `:registry` defaults to 0, `:ncomp` to 1. Registry indices must be
//! non-decreasing so the JS runner can rebuild its grouped registry
//! list with the same flat order. Times and set-bpm carry raw f64 bit
//! patterns (16 hex digits); a control `:value` is four f32 bit patterns
//! (8 hex digits each) — so a case can pin NaN, ±inf, or any tie-break
//! without a float parser in the loop. `(times …)` may repeat and
//! interleave with the other script forms.
//!
//! Golden format (canonical down to the byte — the JS corpus test,
//! `npm/pacer/test/corpus.test.js`, renders the SAME text from
//! `pacer.wasm` output and compares it byte-equal against the same
//! golden; that pair of comparisons IS the native-vs-wasm gate):
//!
//!     ; pacer corpus golden — GENERATED by `zig build corpus -- --update`; do not hand-edit.
//!     (load :ok true)
//!     (meta :bpm "405E000000000000" :beats-per-bar 4
//!       (mtrack :id 0 :target radius :registry 0 :ncomp 1 :source keys :span [S E]
//!         (mkey :at 0 :value ["3E4CCCCD" "0" "0" "0"] :span [S E]))
//!       (mcontrol :index 0 :id knob :target radius :registry 0 :ncomp 1 :type slider
//!         :value [...] :min none :max none :value-span [S E])
//!       (mease :index 1
//!         (mstage :t-end "3F800000" :v-base "00000000" :v-span "3F800000"
//!           (mop :code out_cubic :params ["00000000" "00000000" "00000000" "00000000"])))
//!       (measerefs [0 1]))
//!     (eval :t "3FE0000000000000"
//!       (write :target radius :id 0 :registry 0 :ncomp 1 :value ["3F000000" "00000000" "00000000" "00000000"]))
//!     (set-control :index 0 :value ["3F000000" "00000000" "00000000" "00000000"] :ok true)
//!
//! On a successful load the `(meta …)` block renders the `'PACM'` blob —
//! encoded via `Abi.encodeMeta` then decoded field by field, so the blob
//! LAYOUT sits under the golden (the JS side renders the same text from
//! its decoded `driver.meta`, gating both encoder and decoder). Its
//! floats are hex bit patterns like writes; ticks/spans/counts decimal;
//! `:dur`/`:end` appear together only when the transport has a `:dur`.
//!
//! Each script form echoes its acceptance so rejection semantics are
//! pinned across the boundary: `(set-control … :ok B)`, `(clear-control
//! … :ok B)`, `(set-bpm … :ok B)`, `(register-control … :slot N|none)`.
//!
//! A failed load renders `(load :ok false)` followed by one `(diag …)`
//! per `'PACD'` record (spans already in USER coordinates — rendered
//! from the very blob a wasm host decodes, so diagnostic parity is
//! gated too) and no meta block. An out-of-range clock (non-finite
//! seconds, beyond the 2^53 tick ceiling) renders `(eval :t "…"
//! :out-of-range true)`, mirroring `drv_eval` returning length 0. An
//! empty write buffer closes the `(eval …)` form on its own line.
//!
//! Per-case defects (missing file, malformed harness) fail the case
//! and the run continues — collection over abort, the SJON discipline.
//! Only resource exhaustion aborts.

const std = @import("std");
const sjon = @import("sjon");
const Abi = @import("Abi.zig");
const Compile = @import("Compile.zig");
const Easing = @import("Easing.zig");
const Eval = @import("Eval.zig");
const Writes = @import("Writes.zig");

const Io = std.Io;
const Allocator = std.mem.Allocator;
const Ast = sjon.Ast;
const NodeIndex = Ast.NodeIndex;

/// Corpus files are small documents; anything bigger is a mistake.
const MAX_FILE_BYTES: usize = 1 << 20;

const GENERATED_HEADER =
    "; pacer corpus golden — GENERATED by `zig build corpus -- --update`; do not hand-edit.\n";

pub fn main(init: std.process.Init) !u8 {
    const arena = init.arena.allocator();
    const gpa = init.gpa;
    const io = init.io;

    var stderr_buf: [4096]u8 = undefined;
    var stderr_file = Io.File.stderr();
    var stderr_writer = stderr_file.writer(io, &stderr_buf);
    const out = &stderr_writer.interface;
    defer out.flush() catch {};

    const args = try init.minimal.args.toSlice(arena);
    var corpus_path: ?[]const u8 = null;
    var update = false;
    for (args[1..]) |arg| {
        if (std.mem.eql(u8, arg, "--update")) {
            update = true;
        } else if (corpus_path == null) {
            corpus_path = arg;
        } else {
            try out.print("usage: corpus-runner <corpus-dir> [--update]\n", .{});
            return 2;
        }
    }
    const root = corpus_path orelse {
        try out.print("usage: corpus-runner <corpus-dir> [--update]\n", .{});
        return 2;
    };

    // Collect case directories, sorted — fs iteration order is
    // unspecified and the report should be stable.
    var dir = Io.Dir.cwd().openDir(io, root, .{ .iterate = true }) catch |err| {
        try out.print("corpus: cannot open `{s}`: {s}\n", .{ root, @errorName(err) });
        return 1;
    };
    defer dir.close(io);
    var names: std.ArrayList([]const u8) = .empty;
    var it = dir.iterate();
    while (try it.next(io)) |entry| {
        if (entry.kind != .directory) continue;
        if (entry.name.len == 0 or entry.name[0] == '.') continue;
        try names.append(arena, try arena.dupe(u8, entry.name));
    }
    std.mem.sort([]const u8, names.items, {}, struct {
        fn lessThan(_: void, a: []const u8, b: []const u8) bool {
            return std.mem.lessThan(u8, a, b);
        }
    }.lessThan);
    if (names.items.len == 0) {
        try out.print("corpus: no cases under `{s}`\n", .{root});
        return 1;
    }

    var failed: usize = 0;
    var updated: usize = 0;
    for (names.items) |name| {
        switch (try runCase(gpa, io, out, root, name, update)) {
            .ok => {},
            .updated => updated += 1,
            .failed => failed += 1,
        }
    }

    if (update) {
        try out.print("corpus: {d} case(s), {d} regenerated, {d} failed\n", .{ names.items.len, updated, failed });
    } else {
        try out.print("corpus: {d} case(s), {d} failed\n", .{ names.items.len, failed });
    }
    return if (failed == 0) 0 else 1;
}

const Outcome = enum { ok, updated, failed };

fn runCase(
    gpa: Allocator,
    io: Io,
    out: *Io.Writer,
    root: []const u8,
    name: []const u8,
    update: bool,
) !Outcome {
    // Everything this case allocates dies together.
    var case_arena = std.heap.ArenaAllocator.init(gpa);
    defer case_arena.deinit();
    const a = case_arena.allocator();

    const doc = readCaseFile(a, io, out, root, name, "doc.sjon") orelse return .failed;
    const harness_src = readCaseFile(a, io, out, root, name, "times.sjon") orelse return .failed;
    const harness = (try parseHarness(a, gpa, out, name, harness_src)) orelse return .failed;

    var result = try Compile.compile(gpa, doc, harness.targets);
    defer result.deinit();
    var aw: Io.Writer.Allocating = .init(a);
    defer aw.deinit();
    if (!try renderCase(a, out, name, &aw.writer, &result, harness, doc)) return .failed;
    const actual = aw.toOwnedSlice() catch return error.OutOfMemory;

    const expected_path = try std.fs.path.join(a, &.{ root, name, "expected.sjon" });
    if (update) {
        Io.Dir.cwd().writeFile(io, .{ .sub_path = expected_path, .data = actual }) catch |err| {
            try out.print("corpus: {s}: cannot write expected.sjon: {s}\n", .{ name, @errorName(err) });
            return .failed;
        };
        try out.print("corpus: {s}: regenerated\n", .{name});
        return .updated;
    }

    const expected = readCaseFile(a, io, out, root, name, "expected.sjon") orelse return .failed;
    if (std.mem.eql(u8, expected, actual)) return .ok;
    try reportMismatch(out, name, expected, actual);
    return .failed;
}

fn readCaseFile(
    a: Allocator,
    io: Io,
    out: *Io.Writer,
    root: []const u8,
    name: []const u8,
    file: []const u8,
) ?[:0]u8 {
    const path = std.fs.path.join(a, &.{ root, name, file }) catch return null;
    return Io.Dir.cwd().readFileAllocOptions(io, path, a, .limited(MAX_FILE_BYTES), .of(u8), 0) catch |err| {
        out.print("corpus: {s}: cannot read {s}: {s}\n", .{ name, file, @errorName(err) }) catch {};
        return null;
    };
}

// ---------------------------------------------------------------------------
// Harness — the flat target join + an ordered script
// ---------------------------------------------------------------------------

/// One script form, executed in document order against a live evaluator.
const Step = union(enum) {
    /// One eval at these f64 seconds bits (render-verbatim, `{X:0>16}`).
    eval: u64,
    /// Hold a live control value: f32 bit patterns (echoed verbatim, and
    /// `@bitCast` to f32 for the call — so a lane can pin ±inf/NaN).
    set_control: struct { index: u32, bits: [4]u32 },
    /// Return a control to document authority.
    clear_control: u32,
    /// Live tempo nudge — f64 bits, so a case can pin NaN rejection.
    set_bpm: u64,
    /// Lift a dynamic slot for an unpinned target.
    register_control: struct { target_id: u16, registry: u8, ncomp: u8 },
};

const Harness = struct {
    targets: []const Compile.Target,
    steps: []const Step,
};

/// Parse `times.sjon`. Null = malformed (already reported); the names
/// in the returned targets are duped into `a` and outlive the tree.
fn parseHarness(
    a: Allocator,
    gpa: Allocator,
    out: *Io.Writer,
    name: []const u8,
    src: [:0]const u8,
) !?Harness {
    // Parse never aborts on malformed input (collection over abort) —
    // defects surface as tree diagnostics below.
    var tree = try sjon.parse(gpa, src);
    defer tree.deinit();
    if (tree.hasErrors()) {
        try out.print("corpus: {s}: times.sjon has parse errors\n", .{name});
        return null;
    }

    var targets: std.ArrayList(Compile.Target) = .empty;
    var steps: std.ArrayList(Step) = .empty;
    var last_registry: u8 = 0;
    var seen_script = false;

    for (tree.root) |idx| {
        if (tree.tagOf(idx) != .form) {
            try out.print("corpus: {s}: times.sjon: only (target …) and script forms allowed\n", .{name});
            return null;
        }
        const hdr = tree.formHeader(idx);
        if (std.mem.eql(u8, hdr.head, "target")) {
            if (seen_script) {
                try out.print("corpus: {s}: times.sjon: (target …) forms must precede all script forms\n", .{name});
                return null;
            }
            var target_name: ?[]const u8 = null;
            for (hdr.children) |c| {
                if (tree.tagOf(c) == .symbol) {
                    target_name = tree.symbolText(c);
                    break;
                }
            }
            const tname = target_name orelse {
                try out.print("corpus: {s}: times.sjon: (target …) needs a symbol name\n", .{name});
                return null;
            };
            const ncomp = readSmallInt(&tree, hdr.children, "ncomp", 1) orelse {
                try out.print("corpus: {s}: times.sjon: target `{s}` has a bad :ncomp\n", .{ name, tname });
                return null;
            };
            const registry = readSmallInt(&tree, hdr.children, "registry", 0) orelse {
                try out.print("corpus: {s}: times.sjon: target `{s}` has a bad :registry\n", .{ name, tname });
                return null;
            };
            if (ncomp < 1 or ncomp > 4) {
                try out.print("corpus: {s}: times.sjon: target `{s}` :ncomp must be 1..4\n", .{ name, tname });
                return null;
            }
            if (registry < last_registry) {
                // The JS runner regroups the flat list by registry index;
                // non-decreasing order keeps both flat orders identical.
                try out.print("corpus: {s}: times.sjon: registry indices must be non-decreasing\n", .{name});
                return null;
            }
            last_registry = registry;
            try targets.append(a, .{
                .name = try a.dupe(u8, tname),
                .ncomp = @intCast(ncomp),
                .registry = registry,
            });
        } else if (std.mem.eql(u8, hdr.head, "times")) {
            seen_script = true;
            for (hdr.children) |c| {
                if (tree.tagOf(c) != .string) {
                    try out.print("corpus: {s}: times.sjon: (times …) takes hex strings only\n", .{name});
                    return null;
                }
                const text = tree.stringText(c);
                const bits = parseHexBits(text) orelse {
                    try out.print("corpus: {s}: times.sjon: `{s}` is not 16 hex digits\n", .{ name, text });
                    return null;
                };
                try steps.append(a, .{ .eval = bits });
            }
        } else if (std.mem.eql(u8, hdr.head, "set-control")) {
            seen_script = true;
            const index = readU32(&tree, hdr.children, "index") orelse {
                try out.print("corpus: {s}: times.sjon: (set-control …) needs an integer :index\n", .{name});
                return null;
            };
            const bits = readHexVec4(&tree, hdr.children, "value") orelse {
                try out.print("corpus: {s}: times.sjon: (set-control …) needs :value of four 8-hex f32 lanes\n", .{name});
                return null;
            };
            try steps.append(a, .{ .set_control = .{ .index = index, .bits = bits } });
        } else if (std.mem.eql(u8, hdr.head, "clear-control")) {
            seen_script = true;
            const index = readU32(&tree, hdr.children, "index") orelse {
                try out.print("corpus: {s}: times.sjon: (clear-control …) needs an integer :index\n", .{name});
                return null;
            };
            try steps.append(a, .{ .clear_control = index });
        } else if (std.mem.eql(u8, hdr.head, "set-bpm")) {
            seen_script = true;
            const node = kvNode(&tree, hdr.children, "bpm") orelse {
                try out.print("corpus: {s}: times.sjon: (set-bpm …) needs a :bpm f64-bits string\n", .{name});
                return null;
            };
            if (tree.tagOf(node) != .string) {
                try out.print("corpus: {s}: times.sjon: (set-bpm …) :bpm must be a 16-hex string\n", .{name});
                return null;
            }
            const bits = parseHexBits(tree.stringText(node)) orelse {
                try out.print("corpus: {s}: times.sjon: (set-bpm …) :bpm is not 16 hex digits\n", .{name});
                return null;
            };
            try steps.append(a, .{ .set_bpm = bits });
        } else if (std.mem.eql(u8, hdr.head, "register-control")) {
            seen_script = true;
            const tid = readU32(&tree, hdr.children, "target-id") orelse {
                try out.print("corpus: {s}: times.sjon: (register-control …) needs an integer :target-id\n", .{name});
                return null;
            };
            const registry = readSmallInt(&tree, hdr.children, "registry", 0) orelse {
                try out.print("corpus: {s}: times.sjon: (register-control …) has a bad :registry\n", .{name});
                return null;
            };
            const ncomp = readSmallInt(&tree, hdr.children, "ncomp", 1) orelse {
                try out.print("corpus: {s}: times.sjon: (register-control …) has a bad :ncomp\n", .{name});
                return null;
            };
            if (tid > std.math.maxInt(u16)) {
                try out.print("corpus: {s}: times.sjon: (register-control …) :target-id out of range\n", .{name});
                return null;
            }
            try steps.append(a, .{ .register_control = .{
                .target_id = @intCast(tid),
                .registry = registry,
                .ncomp = ncomp,
            } });
        } else {
            try out.print("corpus: {s}: times.sjon: unknown form `{s}`\n", .{ name, hdr.head });
            return null;
        }
    }

    if (targets.items.len > Abi.MAX_TARGETS) {
        try out.print("corpus: {s}: times.sjon: at most {d} targets\n", .{ name, Abi.MAX_TARGETS });
        return null;
    }
    // Zero host targets is legal: a compose-mode score declares its own
    // via (target …) and compiles standalone; the join then comes wholly
    // from the score (rendered via result.targets, not this host list).
    if (steps.items.len == 0) {
        try out.print("corpus: {s}: times.sjon: no script forms (need at least one (times …) or directive)\n", .{name});
        return null;
    }
    return .{ .targets = targets.items, .steps = steps.items };
}

/// `:key N` from a form's kvpairs as a small non-negative integer;
/// `default` when absent, null when present but malformed.
fn readSmallInt(tree: *const Ast.Tree, children: []const NodeIndex, key: []const u8, default: u8) ?u8 {
    const node = kvNode(tree, children, key) orelse return default;
    const n = switch (tree.tagOf(node)) {
        .number => tree.numberOf(node),
        .number_i64 => @as(f64, @floatFromInt(tree.numberI64Of(node))),
        .number_u64 => @as(f64, @floatFromInt(tree.numberU64Of(node))),
        else => return null,
    };
    if (n < 0 or n > 255 or n != @floor(n)) return null;
    return @intFromFloat(n);
}

/// `:key N` as a non-negative u32; null when absent OR malformed (unlike
/// `readSmallInt`, absence is not a default — these keys are required).
fn readU32(tree: *const Ast.Tree, children: []const NodeIndex, key: []const u8) ?u32 {
    const node = kvNode(tree, children, key) orelse return null;
    const n = switch (tree.tagOf(node)) {
        .number => tree.numberOf(node),
        .number_i64 => @as(f64, @floatFromInt(tree.numberI64Of(node))),
        .number_u64 => @as(f64, @floatFromInt(tree.numberU64Of(node))),
        else => return null,
    };
    if (n < 0 or n > std.math.maxInt(u32) or n != @floor(n)) return null;
    return @intFromFloat(n);
}

/// `:key [ "H8" "H8" "H8" "H8" ]` — four f32 bit patterns; null on any
/// shape or width mismatch.
fn readHexVec4(tree: *const Ast.Tree, children: []const NodeIndex, key: []const u8) ?[4]u32 {
    const node = kvNode(tree, children, key) orelse return null;
    if (tree.tagOf(node) != .vector) return null;
    const elems = tree.vectorElements(node);
    if (elems.len != 4) return null;
    var out: [4]u32 = undefined;
    for (elems, 0..) |e, i| {
        if (tree.tagOf(e) != .string) return null;
        out[i] = parseHexBits32(tree.stringText(e)) orelse return null;
    }
    return out;
}

fn kvNode(tree: *const Ast.Tree, children: []const NodeIndex, key: []const u8) ?NodeIndex {
    for (children) |c| {
        if (tree.tagOf(c) != .kvpair) continue;
        const kv = tree.kvpairHeader(c);
        if (std.mem.eql(u8, kv.key, key)) return kv.value;
    }
    return null;
}

/// Exactly 16 hex digits (either case) → the raw u64 bit pattern.
fn parseHexBits(text: []const u8) ?u64 {
    if (text.len != 16) return null;
    return std.fmt.parseInt(u64, text, 16) catch null;
}

/// Exactly 8 hex digits (either case) → the raw u32 (f32) bit pattern.
fn parseHexBits32(text: []const u8) ?u32 {
    if (text.len != 8) return null;
    return std.fmt.parseInt(u32, text, 16) catch null;
}

// ---------------------------------------------------------------------------
// Canonical rendering — the byte-pinned format
// ---------------------------------------------------------------------------

/// Render the case verdict. False = a defect that voids the golden
/// (already reported), e.g. a control byte in a diagnostic message.
fn renderCase(
    a: Allocator,
    out: *Io.Writer,
    name: []const u8,
    w: *Io.Writer,
    result: *Compile.CompileResult,
    harness: Harness,
    doc: []const u8,
) !bool {
    w.writeAll(GENERATED_HEADER) catch return error.OutOfMemory;
    w.print("(load :ok {})\n", .{result.ok()}) catch return error.OutOfMemory;

    if (!try renderDiags(a, out, name, w, result)) return false;
    if (!result.ok()) return true;

    // The meta block reflects the DOCUMENT — render it before any
    // set-bpm/set-control directive mutates evaluator/transport state.
    try renderMeta(a, w, result, doc);

    var ev = try Eval.Evaluator.init(gpaOf(result), result);
    defer ev.deinit();

    for (harness.steps) |step| switch (step) {
        .eval => |bits| {
            const seconds: f64 = @bitCast(bits);
            const entries = ev.evalSeconds(seconds) catch {
                // drv_eval returns length 0 for an out-of-range clock; the
                // golden pins that the wasm side agrees.
                w.print("(eval :t \"{X:0>16}\" :out-of-range true)\n", .{bits}) catch return error.OutOfMemory;
                continue;
            };
            if (entries.len == 0) {
                w.print("(eval :t \"{X:0>16}\")\n", .{bits}) catch return error.OutOfMemory;
                continue;
            }
            w.print("(eval :t \"{X:0>16}\"", .{bits}) catch return error.OutOfMemory;
            for (entries) |e| {
                std.debug.assert(e.target_id < result.targets.len);
                w.print("\n  (write :target {s} :id {d} :registry {d} :ncomp {d} :value [", .{
                    result.targets[e.target_id].name, e.target_id, e.flags, e.ncomp,
                }) catch return error.OutOfMemory;
                for (e.value, 0..) |lane, c| {
                    const sep = if (c == 0) "" else " ";
                    w.print("{s}\"{X:0>8}\"", .{ sep, @as(u32, @bitCast(lane)) }) catch return error.OutOfMemory;
                }
                w.writeAll("])") catch return error.OutOfMemory;
            }
            w.writeAll(")\n") catch return error.OutOfMemory;
        },
        .set_control => |sc| {
            const value: [4]f32 = .{
                @bitCast(sc.bits[0]), @bitCast(sc.bits[1]), @bitCast(sc.bits[2]), @bitCast(sc.bits[3]),
            };
            const okc = ev.setControl(sc.index, value);
            w.print("(set-control :index {d} :value [", .{sc.index}) catch return error.OutOfMemory;
            for (sc.bits, 0..) |b, c| {
                const sep = if (c == 0) "" else " ";
                w.print("{s}\"{X:0>8}\"", .{ sep, b }) catch return error.OutOfMemory;
            }
            w.print("] :ok {})\n", .{okc}) catch return error.OutOfMemory;
        },
        .clear_control => |index| {
            const okc = ev.clearControl(index);
            w.print("(clear-control :index {d} :ok {})\n", .{ index, okc }) catch return error.OutOfMemory;
        },
        .set_bpm => |bits| {
            const okc = result.setBpm(@bitCast(bits));
            w.print("(set-bpm :bpm \"{X:0>16}\" :ok {})\n", .{ bits, okc }) catch return error.OutOfMemory;
        },
        .register_control => |rc| {
            const slot = ev.registerControl(rc.target_id, rc.registry, rc.ncomp);
            w.print("(register-control :target-id {d} :registry {d} :ncomp {d} :slot ", .{
                rc.target_id, rc.registry, rc.ncomp,
            }) catch return error.OutOfMemory;
            if (slot) |s| {
                w.print("{d})\n", .{s}) catch return error.OutOfMemory;
            } else {
                w.writeAll("none)\n") catch return error.OutOfMemory;
            }
        },
    };
    return true;
}

/// Render the `(meta …)` block from the `'PACM'` blob: encode via
/// `Abi.encodeMeta`, then decode field by field so the packed layout
/// itself sits under the golden. Floats are hex bit patterns; ticks,
/// spans and counts decimal. Track target names resolve through the
/// merged join (`result.targets` — host registries plus compose-mode
/// declarations, so a standalone score's declared-only targets still
/// name); scene names slice from `doc` (the `'SCEN'` records carry only a
/// user-coord span, like tracks — the editor has the source).
fn renderMeta(a: Allocator, w: *Io.Writer, result: *const Compile.CompileResult, doc: []const u8) !void {
    const blob = try a.alloc(u8, Abi.metaEncodedLen(result));
    _ = Abi.encodeMeta(result, blob) catch return error.OutOfMemory;

    const bpm_bits = std.mem.readInt(u64, blob[8..16], .little);
    const dur = std.mem.readInt(i64, blob[16..24], .little);
    const beats_per_bar = std.mem.readInt(u16, blob[24..26], .little);
    const flags = blob[26];
    const track_count = std.mem.readInt(u32, blob[28..32], .little);
    const key_count = std.mem.readInt(u32, blob[32..36], .little);
    const control_count = std.mem.readInt(u32, blob[36..40], .little);

    w.print("(meta :bpm \"{X:0>16}\" :beats-per-bar {d}", .{ bpm_bits, beats_per_bar }) catch return error.OutOfMemory;
    if (flags & 1 != 0) {
        w.print(" :dur {d} :end {s}", .{ dur, if (flags & 2 != 0) "loop" else "hold" }) catch return error.OutOfMemory;
    }

    const keys_base: usize = Abi.META_HEADER_LEN + @as(usize, track_count) * Abi.META_TRACK_LEN;
    var toff: usize = Abi.META_HEADER_LEN;
    for (0..track_count) |_| {
        const rec = blob[toff..][0..Abi.META_TRACK_LEN];
        const target_id = std.mem.readInt(u16, rec[0..2], .little);
        const source = rec[4];
        const key_start = std.mem.readInt(u32, rec[8..12], .little);
        const key_len = std.mem.readInt(u32, rec[12..16], .little);
        w.print("\n  (mtrack :id {d} :target {s} :registry {d} :ncomp {d} :source {s} :span [{d} {d}]", .{
            target_id,                        result.targets[target_id].name,
            rec[2],                           rec[3],
            switch (source) {
                0 => "keys",
                1 => "expr",
                2 => "trigger",
                3 => "pattern",
                else => unreachable,
            },
            std.mem.readInt(u32, rec[16..20], .little), std.mem.readInt(u32, rec[20..24], .little),
        }) catch return error.OutOfMemory;
        for (0..key_len) |k| {
            const krec = blob[keys_base + (@as(usize, key_start) + k) * Abi.META_KEY_LEN ..][0..Abi.META_KEY_LEN];
            w.print("\n    (mkey :at {d} :value [", .{std.mem.readInt(i64, krec[0..8], .little)}) catch return error.OutOfMemory;
            try renderLanes(w, krec[8..24]);
            w.print("] :span [{d} {d}])", .{
                std.mem.readInt(u32, krec[24..28], .little), std.mem.readInt(u32, krec[28..32], .little),
            }) catch return error.OutOfMemory;
        }
        w.writeByte(')') catch return error.OutOfMemory;
        toff += Abi.META_TRACK_LEN;
    }

    var coff: usize = keys_base + @as(usize, key_count) * Abi.META_KEY_LEN;
    for (0..control_count) |i| {
        const rec = blob[coff..][0..Abi.META_CONTROL_LEN];
        const target_id = std.mem.readInt(u16, rec[0..2], .little);
        const cflags = rec[5];
        const id_len = std.mem.readInt(u16, rec[6..8], .little);
        const id = blob[coff + Abi.META_CONTROL_LEN ..][0..id_len];
        w.print("\n  (mcontrol :index {d} :id {s} :target {s} :registry {d} :ncomp {d} :type {s} :value [", .{
            i, id,
            if (target_id == Abi.META_NO_TARGET) "none" else result.targets[target_id].name,
            rec[2], rec[3], controlTypeName(rec[4]),
        }) catch return error.OutOfMemory;
        try renderLanes(w, rec[8..24]);
        w.writeAll("] :min ") catch return error.OutOfMemory;
        try renderRail(w, cflags & 1 != 0, rec[24..40]);
        w.writeAll(" :max ") catch return error.OutOfMemory;
        try renderRail(w, cflags & 2 != 0, rec[40..56]);
        w.print(" :value-span [{d} {d}])", .{
            std.mem.readInt(u32, rec[56..60], .little), std.mem.readInt(u32, rec[60..64], .little),
        }) catch return error.OutOfMemory;
        coff += Abi.META_CONTROL_LEN + id_len;
    }

    // Post-controls section stream (the 'PACM' TLV convention): walk to
    // end-of-buffer, render the 'SCEN' scenes section, skip any unknown
    // id by its length (the tolerance guarantee). `blob.len` is exactly
    // `metaEncodedLen`, so the walk terminates on the last frame.
    var soff: usize = coff;
    while (soff < blob.len) {
        const sid = std.mem.readInt(u32, blob[soff..][0..4], .little);
        const plen = std.mem.readInt(u32, blob[soff + 4 ..][0..4], .little);
        const body = soff + Abi.META_SECTION_HEADER_LEN;
        if (sid == Abi.SCENES_SECTION_ID) {
            const scene_count = std.mem.readInt(u32, blob[body..][0..4], .little);
            var srec: usize = body + 4;
            for (0..scene_count) |_| {
                const rec = blob[srec..][0..Abi.SCENE_REC_LEN];
                const nstart = std.mem.readInt(u32, rec[16..20], .little);
                const nend = std.mem.readInt(u32, rec[20..24], .little);
                w.print("\n  (mscene :name {s} :at {d} :dur {d} :name-span [{d} {d}])", .{
                    doc[nstart..nend],
                    std.mem.readInt(i64, rec[0..8], .little),
                    std.mem.readInt(i64, rec[8..16], .little),
                    nstart,
                    nend,
                }) catch return error.OutOfMemory;
                srec += Abi.SCENE_REC_LEN;
            }
        } else if (sid == Abi.EASE_SECTION_ID) {
            try renderEasePrograms(w, blob[body..][0..plen]);
        }
        soff = body + plen;
    }
    w.writeAll(")\n") catch return error.OutOfMemory;
}

/// Render an `'EASE'` section payload: one `(mease …)` form per compiled
/// program (its live stages/ops with f32-bit weights + params), then a
/// flat `(measerefs …)` list of the per-key program index in key order.
fn renderEasePrograms(w: *Io.Writer, payload: []const u8) !void {
    const prog_count = std.mem.readInt(u32, payload[0..4], .little);
    var poff: usize = 4;
    for (0..prog_count) |pi| {
        const prog = payload[poff..][0..Abi.META_EASE_PROGRAM_LEN];
        const stage_count = prog[0];
        w.print("\n  (mease :index {d}", .{pi}) catch return error.OutOfMemory;
        for (0..stage_count) |si| {
            const st = prog[4 + si * Abi.META_EASE_STAGE_LEN ..][0..Abi.META_EASE_STAGE_LEN];
            w.print("\n    (mstage :t-end \"{X:0>8}\" :v-base \"{X:0>8}\" :v-span \"{X:0>8}\"", .{
                std.mem.readInt(u32, st[0..4], .little),
                std.mem.readInt(u32, st[4..8], .little),
                std.mem.readInt(u32, st[8..12], .little),
            }) catch return error.OutOfMemory;
            const ops_len = st[12];
            for (0..ops_len) |oi| {
                const op = st[16 + oi * Abi.META_EASE_OP_LEN ..][0..Abi.META_EASE_OP_LEN];
                w.print("\n      (mop :code {s} :params [", .{easeOpName(op[0])}) catch return error.OutOfMemory;
                for (0..4) |q| {
                    const sep = if (q == 0) "" else " ";
                    w.print("{s}\"{X:0>8}\"", .{ sep, std.mem.readInt(u32, op[4 + q * 4 ..][0..4], .little) }) catch return error.OutOfMemory;
                }
                w.writeAll("])") catch return error.OutOfMemory;
            }
            w.writeByte(')') catch return error.OutOfMemory; // close mstage
        }
        w.writeByte(')') catch return error.OutOfMemory; // close mease
        poff += Abi.META_EASE_PROGRAM_LEN;
    }
    const ref_count = std.mem.readInt(u32, payload[poff..][0..4], .little);
    poff += 4;
    w.writeAll("\n  (measerefs [") catch return error.OutOfMemory;
    for (0..ref_count) |ri| {
        const sep = if (ri == 0) "" else " ";
        w.print("{s}{d}", .{ sep, std.mem.readInt(u16, payload[poff..][0..2], .little) }) catch return error.OutOfMemory;
        poff += 2;
    }
    w.writeAll("])") catch return error.OutOfMemory;
}

/// The `Easing.Op` tag name for a wire code byte — the golden's stable
/// spelling of an op (mirrored by the npm renderer's `EASE_OPS` table).
fn easeOpName(code: u8) []const u8 {
    return @tagName(@as(Easing.Op, @enumFromInt(code)));
}

/// Four f32 lanes as space-separated `"H8"` bit patterns (no brackets).
fn renderLanes(w: *Io.Writer, bytes: []const u8) !void {
    for (0..4) |i| {
        const bits = std.mem.readInt(u32, bytes[i * 4 ..][0..4], .little);
        const sep = if (i == 0) "" else " ";
        w.print("{s}\"{X:0>8}\"", .{ sep, bits }) catch return error.OutOfMemory;
    }
}

/// A control rail (`:min`/`:max`): `none` when absent, else `[…lanes…]`.
fn renderRail(w: *Io.Writer, present: bool, bytes: []const u8) !void {
    if (!present) {
        w.writeAll("none") catch return error.OutOfMemory;
        return;
    }
    w.writeByte('[') catch return error.OutOfMemory;
    try renderLanes(w, bytes);
    w.writeByte(']') catch return error.OutOfMemory;
}

fn controlTypeName(t: u8) []const u8 {
    return switch (t) {
        0 => "slider",
        1 => "xy",
        2 => "color",
        else => "slider",
    };
}

/// The evaluator wants the gpa the result was compiled with; the
/// `Validated` kept it for exactly this kind of follow-up allocation.
fn gpaOf(result: *const Compile.CompileResult) Allocator {
    return result.validated.gpa;
}

/// Render `(diag …)` lines from the `'PACD'` blob — the same encode
/// path `drv_load` takes, so record order, severity mapping, and the
/// user-coordinate span mapping are all under the golden.
fn renderDiags(
    a: Allocator,
    out: *Io.Writer,
    name: []const u8,
    w: *Io.Writer,
    result: *const Compile.CompileResult,
) !bool {
    var cap: usize = Abi.DIAGS_HEADER_LEN;
    for (result.validated.result.diagnostics) |d| cap += Abi.DIAG_RECORD_LEN + d.message.len;
    for (result.diagnostics) |d| cap += Abi.DIAG_RECORD_LEN + d.message.len;
    const blob_buf = try a.alloc(u8, cap);
    const blob = Abi.encodeDiags(result, blob_buf);

    const count = std.mem.readInt(u32, blob[8..12], .little);
    var pos: usize = Abi.DIAGS_HEADER_LEN;
    for (0..count) |_| {
        const source: []const u8 = if (blob[pos] == 0) "sjon" else "pacer";
        const severity: []const u8 = if (blob[pos + 1] == 0) "error" else "warning";
        const code = std.mem.readInt(u16, blob[pos + 2 ..][0..2], .little);
        const start = std.mem.readInt(u32, blob[pos + 4 ..][0..4], .little);
        const end = std.mem.readInt(u32, blob[pos + 8 ..][0..4], .little);
        const msg_len = std.mem.readInt(u32, blob[pos + 12 ..][0..4], .little);
        const msg = blob[pos + Abi.DIAG_RECORD_LEN ..][0..msg_len];
        pos += Abi.DIAG_RECORD_LEN + msg_len;

        w.print("(diag :source {s} :severity {s} :code {d} :start {d} :end {d} :message \"", .{
            source, severity, code, start, end,
        }) catch return error.OutOfMemory;
        for (msg) |b| {
            if (b < 0x20) {
                try out.print("corpus: {s}: control byte in diagnostic message — not renderable\n", .{name});
                return false;
            }
            if (b == '"' or b == '\\') w.writeByte('\\') catch return error.OutOfMemory;
            w.writeByte(b) catch return error.OutOfMemory;
        }
        w.writeAll("\")\n") catch return error.OutOfMemory;
    }
    return true;
}

