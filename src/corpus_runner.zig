/// First differing line, expected vs actual — enough to see a float
/// drift or a missing write without dumping whole files.
fn reportMismatch(out: *Io.Writer, name: []const u8, expected: []const u8, actual: []const u8) !void {
    var exp_lines = std.mem.splitScalar(u8, expected, '\n');
    var act_lines = std.mem.splitScalar(u8, actual, '\n');
    var line: usize = 1;
    while (true) : (line += 1) {
        const e = exp_lines.next();
        const ac = act_lines.next();
        if (e == null and ac == null) break; // only trailing bytes differ
        if (e != null and ac != null and std.mem.eql(u8, e.?, ac.?)) continue;
        try out.print("corpus: {s}: MISMATCH at line {d}\n  expected: {s}\n  actual:   {s}\n", .{
            name, line, e orelse "<end of file>", ac orelse "<end of file>",
        });
        try out.print("corpus: {s}: `zig build corpus -- --update` regenerates (review the diff)\n", .{name});
        return;
    }
    try out.print("corpus: {s}: MISMATCH (line-identical; byte difference)\n", .{name});
}
