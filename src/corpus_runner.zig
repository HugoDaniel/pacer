const CorpusHarness = @import("corpus_harness");
const Abi = @import("Abi.zig");
const Compile = @import("Compile.zig");
const Driver = @import("Driver.zig");
const Schema = @import("Schema.zig");
const Easing = @import("Easing.zig");
const Eval = @import("Eval.zig");
const Writes = @import("Writes.zig");
const NativeText = @import("NativeText.zig");

const Io = std.Io;
const Allocator = std.mem.Allocator;
const Harness = CorpusHarness.Harness;
const Step = CorpusHarness.Step;

/// Corpus files are small documents; anything bigger is a mistake.
const MAX_FILE_BYTES: usize = 1 << 20;

/// The production writes-zone capacity, derived from the evaluator's own
/// frame-entry ceiling (the same constant both entries size their zone
/// with). Text-adapter frames borrow the static zone; the buffer keeps the
/// source adapter's signature parallel.
const MAX_WRITES: usize = Writes.encodedLen(Eval.MAX_FRAME_ENTRIES);

/// The one fixed TEST-HARNESS-ONLY diagnostic source (binary03 T5b).
/// Shared semantically with `npm/pacer/test/harness.js`; never packed or
/// serialized.
const DIAGNOSTIC_SOURCE: []const u8 = "(transport :bpm 0)\n";

/// `drv_registerControl`'s frozen failure sentinel.
const NO_SLOT: u32 = 0xffff_ffff;

const GENERATED_HEADER =
    "; pacer corpus golden — GENERATED by `zig build corpus -- --update`; do not hand-edit.\n";

pub fn main(init: std.process.Init) !u8 {
    const arena = init.arena.allocator();
    const gpa = init.gpa;
    const io = init.io;

    var stderr_buf: [4096]u8 = undefined;
    var stderr_file = Io.File.stderr();
    var stderr_writer = stderr_file.writer(io, &stderr_buf);
    const out = &stderr_writer.interface;
    defer out.flush() catch {};

    const args = try init.minimal.args.toSlice(arena);
    var corpus_path: ?[]const u8 = null;
    var update = false;
    for (args[1..]) |arg| {
        if (std.mem.eql(u8, arg, "--update")) {
            update = true;
        } else if (corpus_path == null) {
            corpus_path = arg;
        } else {
            try out.print("usage: corpus-runner <corpus-dir> [--update]\n", .{});
            return 2;
        }
    }
    const root = corpus_path orelse {
        try out.print("usage: corpus-runner <corpus-dir> [--update]\n", .{});
        return 2;
    };

    // Collect case directories, sorted — fs iteration order is
    // unspecified and the report should be stable.
    var dir = Io.Dir.cwd().openDir(io, root, .{ .iterate = true }) catch |err| {
        try out.print("corpus: cannot open `{s}`: {s}\n", .{ root, @errorName(err) });
        return 1;
    };
    defer dir.close(io);
    var names: std.ArrayList([]const u8) = .empty;
    var it = dir.iterate();
    while (try it.next(io)) |entry| {
        if (entry.kind != .directory) continue;
        if (entry.name.len == 0 or entry.name[0] == '.') continue;
        try names.append(arena, try arena.dupe(u8, entry.name));
    }
    std.mem.sort([]const u8, names.items, {}, struct {
        fn lessThan(_: void, a: []const u8, b: []const u8) bool {
            return std.mem.lessThan(u8, a, b);
        }
    }.lessThan);
    if (names.items.len == 0) {
        try out.print("corpus: no cases under `{s}`\n", .{root});
        return 1;
    }

    // One preloaded schema for the whole walk — the manifest is parsed
    // and aggregate-validated once, not once per case. Outlives every
    // `Driver` below (the outermost ring of the borrow nesting).
    var schema = try Schema.load(gpa);
    defer schema.deinit();

    // …and one for the harness vocabulary. Two bundles, not one: both
    // declare a `target` form, so a shared schema would make every
    // unqualified `(target …)` `ambiguous_form` in both file kinds.
    var harness_schema = try Schema.loadChecked(gpa, CorpusHarness.manifest_src);
    defer harness_schema.deinit();

    var failed: usize = 0;
    var updated: usize = 0;
    for (names.items) |name| {
        switch (try runCase(gpa, &schema, &harness_schema, io, out, root, name, update)) {
            .ok => {},
            .updated => updated += 1,
            .failed => failed += 1,
        }
    }

    if (update) {
        try out.print("corpus: {d} case(s), {d} regenerated, {d} failed\n", .{ names.items.len, updated, failed });
    } else {
        try out.print("corpus: {d} case(s), {d} failed\n", .{ names.items.len, failed });
    }
    return if (failed == 0) 0 else 1;
}

const Outcome = enum { ok, updated, failed };

fn runCase(
    gpa: Allocator,
    schema: *const Schema,
    harness_schema: *const Schema,
    io: Io,
    out: *Io.Writer,
    root: []const u8,
    name: []const u8,
    update: bool,
) !Outcome {
    // Everything this case allocates dies together.
    var case_arena = std.heap.ArenaAllocator.init(gpa);
    defer case_arena.deinit();
    const a = case_arena.allocator();

    const doc = readCaseFile(a, io, out, root, name, "doc.sjon") orelse return .failed;
    const harness_src = readCaseFile(a, io, out, root, name, "times.sjon") orelse return .failed;
    const harness = (try CorpusHarness.parse(a, gpa, harness_schema, out, name, harness_src)) orelse return .failed;

    // Convert the parser's neutral target records into this consumer's
    // nominal `Compile.Target` type. The per-case arena owns both the names
    // and this slice, and outlives the Driver and its render below.
    const targets = try CorpusHarness.targetsAs(Compile.Target, a, harness);

    // The Driver owns the result/evaluator pair and its teardown order —
    // the borrow-whole rule as structure, not call-site discipline.
    var driver: Driver = undefined;
    try driver.init(gpa, schema, doc, targets);
    defer driver.deinit();
    var aw: Io.Writer.Allocating = .init(a);
    defer aw.deinit();
    if (!try renderCase(a, out, name, &aw.writer, &driver, harness, doc, targets)) return .failed;
    const actual = aw.toOwnedSlice() catch return error.OutOfMemory;

    const expected_path = try std.fs.path.join(a, &.{ root, name, "expected.sjon" });
    if (update) {
        Io.Dir.cwd().writeFile(io, .{ .sub_path = expected_path, .data = actual }) catch |err| {
            try out.print("corpus: {s}: cannot write expected.sjon: {s}\n", .{ name, @errorName(err) });
            return .failed;
        };
        try out.print("corpus: {s}: regenerated\n", .{name});
        return .updated;
    }

    const expected = readCaseFile(a, io, out, root, name, "expected.sjon") orelse return .failed;
    if (std.mem.eql(u8, expected, actual)) return .ok;
    try reportMismatch(out, name, expected, actual);
    return .failed;
}

fn readCaseFile(
    a: Allocator,
    io: Io,
    out: *Io.Writer,
    root: []const u8,
    name: []const u8,
    file: []const u8,
) ?[:0]u8 {
    const path = std.fs.path.join(a, &.{ root, name, file }) catch |err| {
        out.print("corpus: {s}: cannot join path for {s}: {s}\n", .{ name, file, @errorName(err) }) catch {};
        return null;
    };
    return Io.Dir.cwd().readFileAllocOptions(io, path, a, .limited(MAX_FILE_BYTES), .of(u8), 0) catch |err| {
        out.print("corpus: {s}: cannot read {s}: {s}\n", .{ name, file, @errorName(err) }) catch {};
        return null;
    };
}

// ---------------------------------------------------------------------------
// Canonical rendering — the byte-pinned format
// ---------------------------------------------------------------------------

/// Render the case verdict. False = a defect that voids the golden
/// (already reported), e.g. a control byte in a diagnostic message.
pub fn renderCase(
    a: Allocator,
    out: *Io.Writer,
    name: []const u8,
    w: *Io.Writer,
    driver: *Driver,
    harness: Harness,
    doc: []const u8,
    targets: []const Compile.Target,
) !bool {
    const result = &driver.result;
    w.writeAll(GENERATED_HEADER) catch return error.OutOfMemory;
    w.print("(load :ok {})\n", .{result.ok()}) catch return error.OutOfMemory;

    if (!try renderDiags(a, out, name, w, result)) return false;
    if (!result.ok()) return true;

    // A lifecycle script executes the WHOLE script through the actual
    // `drv_*` entry; ordinary scripts keep the existing source-local
    // evaluator path byte-for-byte.
    if (hasLifecycle(harness.steps)) {
        return renderLifecycle(a, out, name, w, driver, harness, doc, targets);
    }

    // The meta block reflects the DOCUMENT: it is encoded from the table,
    // which no directive can touch — set-bpm and set-control are evaluator
    // state. Rendered first so the golden reads top-down.
    try renderMeta(a, w, result, doc);

    var source = SourceAdapter{ .ev = &driver.evaluator.? };
    return renderSteps(out, name, w, result, &source, harness.steps);
}

/// True iff the script contains a second-load / registry lifecycle form.
/// Such a case is text-first but not a pure `Driver` replay: the actual
/// production `drv_*` session must execute every ordinary step too.
fn hasLifecycle(steps: []const Step) bool {
    for (steps) |step| switch (step) {
        .reload, .registry_mismatch => return true,
        else => {},
    };
    return false;
}

// ---------------------------------------------------------------------------
// Step execution adapters — one formatter, two real executors
// ---------------------------------------------------------------------------

const Frame = union(enum) {
    /// A valid `'PACW'` frame, borrowed until the next call.
    entries: []const Writes.Entry,
    /// `drv_eval` returned zero for an out-of-range host clock.
    out_of_range,
    /// The real text session is unloaded (a diagnostic reload); it is
    /// distinct from a clock-range rejection even though both return 0.
    unloaded,
};

const ReloadEcho = union(enum) {
    status: struct { status: u32, loaded: bool },
    binary_only,
};

/// The existing source-local replay: the corpus runner's `Driver`
/// evaluator, unchanged. Lifecycle forms never reach this adapter.
const SourceAdapter = struct {
    ev: *Eval.Evaluator,

    fn evalStep(self: *SourceAdapter, bits: u64, _: *[MAX_WRITES]u8) !Frame {
        const seconds: f64 = @bitCast(bits);
        const entries = self.ev.evalSeconds(seconds) catch return .out_of_range;
        return .{ .entries = entries };
    }

    fn setControl(self: *SourceAdapter, index: u32, value: [4]f32) bool {
        return self.ev.setControl(index, value);
    }

    fn clearControl(self: *SourceAdapter, index: u32) bool {
        return self.ev.clearControl(index);
    }

    fn setBpm(self: *SourceAdapter, bpm: f64) bool {
        return self.ev.setBpm(bpm);
    }

    fn registerControl(self: *SourceAdapter, target_id: u16, registry: u8, ncomp: u8) ?u32 {
        const slot = self.ev.registerControl(target_id, registry, ncomp) orelse return null;
        return @intCast(slot);
    }

    fn reload(_: *SourceAdapter, _: CorpusHarness.ReloadKind) anyerror!ReloadEcho {
        unreachable; // only lifecycle scripts use the text adapter
    }
};

/// The actual production text session, reached only through the std-only
/// `NativeText` extern facade into the separately compiled object. The
/// original document and canonical host join are kept so `current` can
/// restore exactly the authored input.
const TextAdapter = struct {
    doc: []const u8,
    pact: []const u8,
    loaded: bool = false,

    fn evalStep(self: *TextAdapter, bits: u64, _: *[MAX_WRITES]u8) !Frame {
        const len = NativeText.evalSeconds(@bitCast(bits));
        if (len == 0) return if (self.loaded) .out_of_range else .unloaded;
        const ptr: [*]align(4) const u8 = @alignCast(NativeText.writesPtr());
        const entries = Writes.decode(ptr[0..len]) orelse return error.CorruptProductionWrites;
        return .{ .entries = entries };
    }

    fn setControl(self: *TextAdapter, index: u32, value: [4]f32) bool {
        _ = self;
        return NativeText.setControl(index, value[0], value[1], value[2], value[3]) == 0;
    }

    fn clearControl(self: *TextAdapter, index: u32) bool {
        _ = self;
        return NativeText.clearControl(index) == 0;
    }

    fn setBpm(self: *TextAdapter, bpm: f64) bool {
        _ = self;
        return NativeText.setBpm(bpm) == 0;
    }

    fn registerControl(self: *TextAdapter, target_id: u16, registry: u8, ncomp: u8) ?u32 {
        _ = self;
        const slot = NativeText.registerControl(target_id, registry, ncomp);
        return if (slot == NO_SLOT) null else slot;
    }

    fn reload(self: *TextAdapter, kind: CorpusHarness.ReloadKind) anyerror!ReloadEcho {
        switch (kind) {
            .bad_call => {
                // Over-cap document length: the production validation runs
                // before any teardown, so the live score/state survives.
                // Preserve the state that was actually current: a bad call
                // after a diagnostic reload keeps the text session unloaded
                // instead of requiring a live score.
                // Nothing out of bounds is read or copied.
                const was_loaded = self.loaded;
                const status = NativeText.load(NativeText.docCap() + 1, 0);
                if (status != 2) return error.UnexpectedTextStatus;
                if (self.loaded != was_loaded) return error.UnexpectedTextState;
                return .{ .status = .{ .status = status, .loaded = was_loaded } };
            },
            .diagnostics => {
                if (DIAGNOSTIC_SOURCE.len > NativeText.docCap()) return error.OverCap;
                @memcpy(NativeText.docPtr()[0..DIAGNOSTIC_SOURCE.len], DIAGNOSTIC_SOURCE);
                @memcpy(NativeText.targetsPtr()[0..self.pact.len], self.pact);
                const status = NativeText.load(
                    @intCast(DIAGNOSTIC_SOURCE.len),
                    @intCast(self.pact.len),
                );
                if (status != 1) return error.UnexpectedTextStatus;
                self.loaded = false;
                if (NativeText.metaLen() != 0) return error.UnexpectedTextState;
                if (NativeText.diagLen() <= Abi.DIAGS_HEADER_LEN) return error.UnexpectedTextState;
                return .{ .status = .{ .status = status, .loaded = false } };
            },
            .bad_version => return .binary_only,
            .current => {
                if (self.doc.len > NativeText.docCap()) return error.OverCap;
                @memcpy(NativeText.docPtr()[0..self.doc.len], self.doc);
                @memcpy(NativeText.targetsPtr()[0..self.pact.len], self.pact);
                const status = NativeText.load(@intCast(self.doc.len), @intCast(self.pact.len));
                if (status != 0) return error.UnexpectedTextStatus;
                self.loaded = true;
                return .{ .status = .{ .status = status, .loaded = true } };
            },
        }
    }
};

/// One formatter for every script step. `adapter` supplies only execution
/// results; all canonical text is written here, so the source and actual
/// text paths cannot drift in spelling.
fn renderSteps(
    out: *Io.Writer,
    name: []const u8,
    w: *Io.Writer,
    result: *const Compile.CompileResult,
    adapter: anytype,
    steps: []const Step,
) !bool {
    var frame_buf: [MAX_WRITES]u8 = undefined;
    for (steps) |step| switch (step) {
        .eval => |bits| {
            const frame = try adapter.evalStep(bits, &frame_buf);
            switch (frame) {
                .entries => |entries| {
                    if (entries.len == 0) {
                        w.print("(eval :t \"{X:0>16}\")\n", .{bits}) catch return error.OutOfMemory;
                        continue;
                    }
                    w.print("(eval :t \"{X:0>16}\"", .{bits}) catch return error.OutOfMemory;
                    for (entries) |e| {
                        std.debug.assert(e.target_id < result.targets.len);
                        w.print("\n  (write :target {s} :id {d} :registry {d} :ncomp {d} :value [", .{
                            result.targets[e.target_id].name, e.target_id, e.flags, e.ncomp,
                        }) catch return error.OutOfMemory;
                        for (e.value, 0..) |lane, c| {
                            const sep = if (c == 0) "" else " ";
                            w.print("{s}\"{X:0>8}\"", .{ sep, @as(u32, @bitCast(lane)) }) catch return error.OutOfMemory;
                        }
                        w.writeAll("])") catch return error.OutOfMemory;
                    }
                    w.writeAll(")\n") catch return error.OutOfMemory;
                },
                .out_of_range => {
                    w.print("(eval :t \"{X:0>16}\" :out-of-range true)\n", .{bits}) catch return error.OutOfMemory;
                },
                .unloaded => {
                    w.print("(eval :t \"{X:0>16}\" :unloaded true)\n", .{bits}) catch return error.OutOfMemory;
                },
            }
        },
        .set_control => |sc| {
            const value: [4]f32 = .{
                @bitCast(sc.bits[0]), @bitCast(sc.bits[1]), @bitCast(sc.bits[2]), @bitCast(sc.bits[3]),
            };
            const okc = adapter.setControl(sc.index, value);
            w.print("(set-control :index {d} :value [", .{sc.index}) catch return error.OutOfMemory;
            for (sc.bits, 0..) |b, c| {
                const sep = if (c == 0) "" else " ";
                w.print("{s}\"{X:0>8}\"", .{ sep, b }) catch return error.OutOfMemory;
            }
            w.print("] :ok {})\n", .{okc}) catch return error.OutOfMemory;
        },
        .clear_control => |index| {
            const okc = adapter.clearControl(index);
            w.print("(clear-control :index {d} :ok {})\n", .{ index, okc }) catch return error.OutOfMemory;
        },
        .set_bpm => |bits| {
            const okc = adapter.setBpm(@bitCast(bits));
            w.print("(set-bpm :bpm \"{X:0>16}\" :ok {})\n", .{ bits, okc }) catch return error.OutOfMemory;
        },
        .register_control => |rc| {
            const slot = adapter.registerControl(rc.target_id, rc.registry, rc.ncomp);
            w.print("(register-control :target-id {d} :registry {d} :ncomp {d} :slot ", .{
                rc.target_id, rc.registry, rc.ncomp,
            }) catch return error.OutOfMemory;
            if (slot) |s| {
                w.print("{d})\n", .{s}) catch return error.OutOfMemory;
            } else {
                w.writeAll("none)\n") catch return error.OutOfMemory;
            }
        },
        .reload => |kind| {
            const echo = adapter.reload(kind) catch |err| switch (err) {
                error.UnexpectedTextStatus, error.UnexpectedTextState => {
                    try out.print("corpus: {s}: text lifecycle {s} did not match the production contract\n", .{ name, kind.spelling() });
                    return false;
                },
                else => return err,
            };
            switch (echo) {
                .status => |st| w.print("(reload :kind {s} :status {d} :loaded {})\n", .{
                    kind.spelling(), st.status, st.loaded,
                }) catch return error.OutOfMemory,
                .binary_only => w.print("(reload :kind {s} :skipped binary-only)\n", .{kind.spelling()}) catch
                    return error.OutOfMemory,
            }
        },
        .registry_mismatch => |mode| {
            // Text has no PACT-vs-PACB registry gate; the binary leg owns it.
            w.print("(registry-mismatch :mode {s} :skipped binary-only)\n", .{mode.spelling()}) catch
                return error.OutOfMemory;
        },
    };
    return true;
}

/// Text-first lifecycle rendering: run the ACTUAL production `drv_*`
/// session for the whole script. The initial local `Driver` compile stays
/// the independent byte oracle for the first PACM; after a diagnostic
/// reload, frames/status/metadata come from the real loader.
fn renderLifecycle(
    a: Allocator,
    out: *Io.Writer,
    name: []const u8,
    w: *Io.Writer,
    driver: *Driver,
    harness: Harness,
    doc: []const u8,
    targets: []const Compile.Target,
) !bool {
    var text = TextAdapter{ .doc = doc, .pact = "" };
    defer NativeText.reset();
    NativeText.reset();

    // Canonical 'PACT' of the ORIGINAL host join (never result.targets,
    // which may include compose-mode declarations).
    const pact_buf = try a.alloc(u8, Abi.targetsEncodedLen(targets));
    text.pact = Abi.encodeTargets(targets, pact_buf) catch unreachable;

    if (doc.len > NativeText.docCap() or text.pact.len > NativeText.targetsCap()) {
        try out.print("corpus: {s}: document/PACT exceeds the text zones\n", .{name});
        return false;
    }
    @memcpy(NativeText.docPtr()[0..doc.len], doc);
    @memcpy(NativeText.targetsPtr()[0..text.pact.len], text.pact);
    const status = NativeText.load(@intCast(doc.len), @intCast(text.pact.len));
    if (status != 0) {
        try out.print("corpus: {s}: actual text load status {d}, expected 0\n", .{ name, status });
        return false;
    }
    text.loaded = true;

    // The independent local compile's fresh PACM must equal the actual
    // production load's bytes before the golden renders them.
    const want_meta = try a.alloc(u8, Abi.metaEncodedLen(&driver.result));
    _ = Abi.encodeMeta(&driver.result, want_meta) catch unreachable;
    const got_meta = NativeText.metaPtr()[0..NativeText.metaLen()];
    if (!std.mem.eql(u8, want_meta, got_meta)) {
        try out.print("corpus: {s}: actual text PACM differs from the local oracle\n", .{name});
        return false;
    }
    try renderMetaBlob(w, got_meta, &driver.result, doc);

    return renderSteps(out, name, w, &driver.result, &text, harness.steps);
}

/// Render the `(meta …)` block from the `'PACM'` blob: encode via
/// `Abi.encodeMeta`, then decode field by field so the packed layout
/// itself sits under the golden. Floats are hex bit patterns; ticks,
/// spans and counts decimal. Track target names resolve through the
/// merged join (`result.targets` — host registries plus compose-mode
/// declarations, so a standalone score's declared-only targets still
/// name); scene names slice from `doc` (the `'SCEN'` records carry only a
/// user-coord span, like tracks — the editor has the source).
fn renderMeta(a: Allocator, w: *Io.Writer, result: *const Compile.CompileResult, doc: []const u8) !void {
    const blob = try a.alloc(u8, Abi.metaEncodedLen(result));
    // Sized exactly by `metaEncodedLen` — BufferTooSmall here would be
    // an encoder accounting bug, not a resource condition. The decode
    // likewise reads our own bytes, so a null is an encoder/decoder
    // disagreement, which is the thing this pairing exists to catch.
    _ = Abi.encodeMeta(result, blob) catch unreachable;
    try renderMetaBlob(w, blob, result, doc);
}

/// Render a `'PACM'` blob already produced by the path under test. The
/// lifecycle anchor passes the ACTUAL production load's bytes here (after
/// the local oracle equality check); ordinary cases pass their own encode.
fn renderMetaBlob(
    w: *Io.Writer,
    blob: []const u8,
    result: *const Compile.CompileResult,
    doc: []const u8,
) !void {
    const m = Abi.decodeMeta(blob) orelse unreachable;

    w.print("(meta :bpm \"{X:0>16}\" :beats-per-bar {d}", .{
        @as(u64, @bitCast(m.bpm)), m.beats_per_bar,
    }) catch return error.OutOfMemory;
    if (m.dur) |dur| {
        w.print(" :dur {d} :end {s}", .{ dur, if (m.end_loop) "loop" else "hold" }) catch return error.OutOfMemory;
    }

    for (0..m.track_count) |ti| {
        const track = m.track(ti);
        w.print("\n  (mtrack :id {d} :target {s} :registry {d} :ncomp {d} :source {s} :span [{d} {d}]", .{
            track.target_id,
            result.targets[track.target_id].name,
            track.registry,
            track.ncomp,
            @tagName(track.source),
            track.span.start,
            track.span.end,
        }) catch return error.OutOfMemory;
        for (0..track.key_len) |k| {
            const key = m.key(track.key_start + k);
            w.print("\n    (mkey :at {d} :value [", .{key.at}) catch return error.OutOfMemory;
            try renderLanes(w, key.value);
            w.print("] :span [{d} {d}])", .{ key.span.start, key.span.end }) catch return error.OutOfMemory;
        }
        w.writeByte(')') catch return error.OutOfMemory;
    }

    var controls = m.controls();
    var ci: usize = 0;
    while (controls.next()) |ctl| : (ci += 1) {
        w.print("\n  (mcontrol :index {d} :id {s} :target {s} :registry {d} :ncomp {d} :type {s} :value [", .{
            ci,
            ctl.id,
            if (ctl.target_id) |id| result.targets[id].name else "none",
            ctl.registry,
            ctl.ncomp,
            @tagName(ctl.kind),
        }) catch return error.OutOfMemory;
        try renderLanes(w, ctl.value);
        w.writeAll("] :min ") catch return error.OutOfMemory;
        try renderRail(w, ctl.min);
        w.writeAll(" :max ") catch return error.OutOfMemory;
        try renderRail(w, ctl.max);
        w.print(" :value-span [{d} {d}])", .{ ctl.value_span.start, ctl.value_span.end }) catch return error.OutOfMemory;
    }

    // The post-controls sections, in the encoder's fixed order —
    // 'SCEN', 'EASE', 'TMPO'. An absent section reads as an empty one,
    // so a score without scenes / easing / a tempo map renders nothing
    // here, exactly as the omit-when-empty encoding intends.
    for (0..m.sceneCount()) |si| {
        const scene = m.scene(si);
        w.print("\n  (mscene :name {s} :at {d} :dur {d} :name-span [{d} {d}])", .{
            doc[scene.name_span.start..scene.name_span.end],
            scene.start_tick,
            scene.dur_ticks,
            scene.name_span.start,
            scene.name_span.end,
        }) catch return error.OutOfMemory;
    }
    try renderEasePrograms(w, &m);
    for (0..m.tempoCount()) |i| {
        // Tempo segments (including segment 0): ticks decimal, bpm
        // as an f64 bit pattern like the transport's own :bpm.
        const seg = m.tempoSeg(i);
        w.print("\n  (mtempo :tick {d} :bpm \"{X:0>16}\")", .{
            seg.tick, @as(u64, @bitCast(seg.bpm)),
        }) catch return error.OutOfMemory;
    }
    w.writeAll(")\n") catch return error.OutOfMemory;
}

/// Render the `'EASE'` section: one `(mease …)` form per compiled
/// program (its live stages/ops with f32-bit weights + params), then a
/// flat `(measerefs …)` list of the per-key program index in key order.
/// Renders nothing when the section is absent (a linear-only score).
fn renderEasePrograms(w: *Io.Writer, m: *const Abi.MetaView) !void {
    const prog_count = m.easeProgramCount();
    if (prog_count == 0) return;
    for (0..prog_count) |pi| {
        const prog = m.easeProgram(pi);
        w.print("\n  (mease :index {d}", .{pi}) catch return error.OutOfMemory;
        for (prog.stages[0..prog.len]) |stage| {
            w.print("\n    (mstage :t-end \"{X:0>8}\" :v-base \"{X:0>8}\" :v-span \"{X:0>8}\"", .{
                @as(u32, @bitCast(stage.t_end)),
                @as(u32, @bitCast(stage.v_base)),
                @as(u32, @bitCast(stage.v_span)),
            }) catch return error.OutOfMemory;
            for (stage.ops[0..stage.ops_len]) |op| {
                w.print("\n      (mop :code {s} :params [", .{@tagName(op.code)}) catch return error.OutOfMemory;
                try renderLanes(w, op.params);
                w.writeAll("])") catch return error.OutOfMemory;
            }
            w.writeByte(')') catch return error.OutOfMemory; // close mstage
        }
        w.writeByte(')') catch return error.OutOfMemory; // close mease
    }
    w.writeAll("\n  (measerefs [") catch return error.OutOfMemory;
    for (0..m.easeRefCount()) |ri| {
        const sep = if (ri == 0) "" else " ";
        w.print("{s}{d}", .{ sep, m.easeRef(ri) }) catch return error.OutOfMemory;
    }
    w.writeAll("])") catch return error.OutOfMemory;
}

/// Four f32 lanes as space-separated `"H8"` bit patterns (no brackets).
fn renderLanes(w: *Io.Writer, lanes: [4]f32) !void {
    for (lanes, 0..) |lane, i| {
        const sep = if (i == 0) "" else " ";
        w.print("{s}\"{X:0>8}\"", .{ sep, @as(u32, @bitCast(lane)) }) catch return error.OutOfMemory;
    }
}

/// A control rail (`:min`/`:max`): `none` when absent, else `[…lanes…]`.
fn renderRail(w: *Io.Writer, rail: ?[4]f32) !void {
    const lanes = rail orelse {
        w.writeAll("none") catch return error.OutOfMemory;
        return;
    };
    w.writeByte('[') catch return error.OutOfMemory;
    try renderLanes(w, lanes);
    w.writeByte(']') catch return error.OutOfMemory;
}

/// Render `(diag …)` lines from the `'PACD'` blob — the same encode
/// path `drv_load` takes, so record order, severity mapping, and the
/// score-coordinate spans are all under the golden.
fn renderDiags(
    a: Allocator,
    out: *Io.Writer,
    name: []const u8,
    w: *Io.Writer,
    result: *const Compile.CompileResult,
) !bool {
    // Sized by the encoder's own accounting, so `encodeDiags` can never
    // silently drop a record from the golden.
    const blob_buf = try a.alloc(u8, Abi.diagsEncodedLen(result));
    const blob = Abi.encodeDiags(result, blob_buf);
    std.debug.assert(blob.len == blob_buf.len);
    const view = Abi.decodeDiags(blob) orelse unreachable;

    var records = view.records();
    while (records.next()) |d| {
        w.print("(diag :source {s} :severity {s} :code {d} :start {d} :end {d} :message \"", .{
            @tagName(d.source), if (d.severity == .err) "error" else "warning",
            d.code,             d.span.start,
            d.span.end,
        }) catch return error.OutOfMemory;
        for (d.message) |b| {
            if (b < 0x20) {
                try out.print("corpus: {s}: control byte in diagnostic message — not renderable\n", .{name});
                return false;
            }
            if (b == '"' or b == '\\') w.writeByte('\\') catch return error.OutOfMemory;
            w.writeByte(b) catch return error.OutOfMemory;
        }
        w.writeAll("\")\n") catch return error.OutOfMemory;
    }
    return true;
}

