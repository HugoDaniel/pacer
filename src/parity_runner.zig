//! Native playback-parity runner and total corpus classifier — binary03 T3
//! (plan 03 P1).
//!
//! This is a CONSUMER executable, like the CLI: it imports the actual public
//! `pacer` module and the named std/SJON `corpus_harness` leaf, and it never
//! imports a pacer core/runtime source file. The production playback runtime
//! is compiled separately from `src/native_rt_bridge.zig` and linked as
//! `native_rt_object`; every runtime call below goes through the std-only
//! `NativeRt.zig` extern facade to the single real `prt_*` definitions.
//!
//! ## Classification is algorithmic, never name-based
//!
//! The corpus walk is sorted. For each `corpus/<case>/`:
//!
//!   1. read bounded `doc.sjon`, `times.sjon`, and `expected.sjon` (a
//!      symlinked document is followed, as the corpus runner does);
//!   2. parse the harness through `CorpusHarness.parse` and convert its
//!      neutral target records into the public `pacer.Compile.Target` type;
//!   3. compile with the case's actual host join through a stationary public
//!      `pacer.Driver`;
//!   4. require the actual compile outcome to agree with the golden's ONE
//!      initial `(load :ok true|false)` record — later `(load …)` records are
//!      reloads, never the initial classification;
//!   5. inspect the compiled track source TAGS (never source substrings or
//!      case names) to distinguish a clean pattern case.
//!
//! Every case is assigned exactly once:
//!
//!   - clean non-pattern: pack, then replay the production loader and compare
//!     complete `'PACM'`/`'PACW'` bytes plus control/BPM/registration results;
//!   - clean pattern: explicit `skipped-pending-SJON`; the existing
//!     `pack_patterns_unsupported` preflight refusal is asserted and `encode`
//!     is never called;
//!   - load-failing: the compile refusal is asserted; `preflight`/`encode`
//!     are never called, so no `'PACB'` bytes can be produced.
//!
//! Any missing/malformed golden, unknown golden/harness record, compile/golden
//! disagreement, unexplained non-pattern preflight refusal, or unclassified
//! case fails that case; totals are calculated from the results. A skip is
//! reported separately and is never counted as a pass.
//!
//! ## Replay
//!
//! The canonical `'PACT'` of the ORIGINAL host join is encoded first (never
//! `result.targets`, which includes compose-mode declarations). Lengths are
//! checked against the production zone caps before copy/narrow; bytes are
//! copied into the real zones; the real `prt_load` must return 0. The three
//! metadata spellings are compared complete:
//!
//!     fresh Abi.encodeMeta(text CompileResult)
//!         == embedded 'PACM' section
//!         == NativeRt.metaPtr()[0..NativeRt.metaLen()]
//!
//! Then every current harness step runs in document order on both paths.
//! Authored seconds are the exact authored `u64` bit pattern (`@bitCast`),
//! never reinterpreted through tick conversion. Text entries are encoded with
//! the public `Writes.encode`; the complete production `'PACW'` blob is
//! compared, including header, count, ordering, flags, ncomp, and every lane.
//! A status-0 text eval that produces an EMPTY frame encodes a 12-byte header
//! and is therefore distinct from the production zero return (out-of-range /
//! unloaded). Controls, BPM, registration (normalizing `null` to the frozen
//! `0xffff_ffff` sentinel), and the expr-failure counter are compared after
//! the same sequence.
//!
//! Every byte mismatch names the case, script-step index, surface, both
//! lengths, and the first differing byte offset with both byte values (or
//! `end-of-buffer`).
//!
//! The runtime global is reset before and after every case/error; there is
//! exactly one production runtime and one materializer. No source text is ever
//! injected into runtime metadata. There is no `--update`: this verb only
//! measures and reports.

const std = @import("std");
const pacer = @import("pacer");
const CorpusHarness = @import("corpus_harness");
const sjon = @import("sjon");
const NativeRt = @import("NativeRt.zig");

const Io = std.Io;
const Allocator = std.mem.Allocator;
const Harness = CorpusHarness.Harness;
const Step = CorpusHarness.Step;

/// Corpus files are small documents; anything bigger is a mistake.
const MAX_FILE_BYTES: usize = 1 << 20;

/// The first line every generated golden carries. The initial `(load …)`
/// record must be the very next non-comment record.
pub const GENERATED_HEADER =
    "; pacer corpus golden — GENERATED by `zig build corpus -- --update`; do not hand-edit.";

/// The frozen production registration failure sentinel (`rt_entry.NO_SLOT`).
const NO_SLOT: u32 = 0xffff_ffff;

/// The production writes-zone capacity, derived from the evaluator's own
/// frame-entry ceiling (the same constant `rt_entry` sizes its zone with).
const MAX_WRITES: usize = pacer.Writes.encodedLen(pacer.EvalCore.MAX_FRAME_ENTRIES);

/// One committed outcome of pack orchestration. `compile_refused` and
/// `preflight_refused` are deliberately separate: a diagnostic fixture is
/// refused BEFORE either asserted pack API is called, while a pattern fixture
/// may reach `preflight` but never `encode`.
pub const Packed = union(enum) {
    compile_refused,
    preflight_refused: []const pacer.Compile.Diagnostic,
    encoded: []const u8,
};

/// The three exhaustive classes of a corpus case.
pub const Class = enum { clean_non_pattern, clean_pattern, load_failing };

pub const GoldenError = error{
    MalformedHeader,
    MissingInitialLoad,
    MalformedLoadRecord,
    DuplicateInitialLoad,
    UnknownTopLevelForm,
    MalformedGolden,
};

pub const ClassifyError = error{CompileGoldenDisagreement};

/// One golden's classification input: the ONE initial load record. Later
/// `(load …)` reload records are intentionally ignored here — they are a
/// different surface and must never be mistaken for the initial outcome.
pub const Golden = struct { initial_ok: bool };

/// Measured totals. `clean_pattern` is a SKIP count, never a pass count.
pub const Totals = struct {
    total: usize = 0,
    clean_non_pattern: usize = 0,
    clean_pattern: usize = 0,
    load_failing: usize = 0,
    failed: usize = 0,
};

pub fn main(init: std.process.Init) !u8 {
    const arena = init.arena.allocator();
    const gpa = init.gpa;
    const io = init.io;

    var stderr_buf: [4096]u8 = undefined;
    var stderr_file = Io.File.stderr();
    var stderr_writer = stderr_file.writer(io, &stderr_buf);
    const out = &stderr_writer.interface;
    defer out.flush() catch {};

    const args = try init.minimal.args.toSlice(arena);
    // Exactly one corpus directory. No `--update`, no forwarded build args:
    // this verb measures, it never regenerates.
    if (args.len != 2 or std.mem.eql(u8, args[1], "--update") or std.mem.startsWith(u8, args[1], "-")) {
        try out.print("usage: parity-runner <corpus-dir>\n", .{});
        try out.print("parity: extra arguments (including --update) are rejected\n", .{});
        return 2;
    }

    const totals = runAll(gpa, io, out, args[1]) catch |err| switch (err) {
        error.OutOfMemory => return err,
        else => {
            try out.print("parity: run failed: {s}\n", .{@errorName(err)});
            return 1;
        },
    };
    return if (totals.failed == 0) 0 else 1;
}

/// Walk the corpus once. A case failure increments `failed` and the walk
/// continues (collection over abort); only resource exhaustion aborts.
pub fn runAll(gpa: Allocator, io: Io, out: *Io.Writer, root: []const u8) !Totals {
    var dir = Io.Dir.cwd().openDir(io, root, .{ .iterate = true }) catch |err| {
        try out.print("parity: cannot open `{s}`: {s}\n", .{ root, @errorName(err) });
        return error.CorpusUnavailable;
    };
    defer dir.close(io);

    // Case names live in a small local arena; the walk's schemas/evaluators
    // own everything else. Nothing here retains the caller's GPA.
    var names_arena = std.heap.ArenaAllocator.init(gpa);
    defer names_arena.deinit();
    const na = names_arena.allocator();

    var names: std.ArrayList([]const u8) = .empty;
    var it = dir.iterate();
    while (try it.next(io)) |entry| {
        if (entry.kind != .directory) continue;
        if (entry.name.len == 0 or entry.name[0] == '.') continue;
        try names.append(na, try na.dupe(u8, entry.name));
    }
    std.mem.sort([]const u8, names.items, {}, struct {
        fn lessThan(_: void, a: []const u8, b: []const u8) bool {
            return std.mem.lessThan(u8, a, b);
        }
    }.lessThan);
    if (names.items.len == 0) {
        try out.print("parity: no cases under `{s}`\n", .{root});
        return error.CorpusUnavailable;
    }

    // Host-level schemas, one each for the whole walk — the outermost ring of
    // the compile borrow nesting. The score schema comes through public
    // `pacer`; the harness vocabulary through the named leaf's own embedded
    // manifest (never composed with the score schema).
    var schema = try pacer.Schema.load(gpa);
    defer schema.deinit();

    var hs: struct { preloaded: sjon.Host.PreloadedSchema } = .{
        .preloaded = try sjon.Host.preloadSchema(gpa, &.{CorpusHarness.manifest_src}),
    };
    defer hs.preloaded.deinit();
    if (hs.preloaded.diagnostics.len != 0) {
        try out.print("parity: corpus harness manifest preload produced {d} diagnostic(s)\n", .{hs.preloaded.diagnostics.len});
        for (hs.preloaded.diagnostics) |d| {
            try out.print("  {s}: {d}..{d}: {s}\n", .{ @tagName(d.code), d.span.start, d.span.end, d.message });
        }
        return error.HarnessManifestInvalid;
    }

    var totals: Totals = .{};
    for (names.items) |name| {
        totals.total += 1;
        runCase(gpa, io, out, &schema, &hs, root, name, &totals) catch |err| switch (err) {
            error.OutOfMemory => return err,
            else => totals.failed += 1,
        };
    }

    try out.print("parity: {d} case(s), {d} failed\n", .{ totals.total, totals.failed });
    try out.print(
        "parity: clean non-pattern {d} replayed; clean pattern {d} skipped-pending-SJON (not passes); load-failing {d} compile-refused (no PACB)\n",
        .{ totals.clean_non_pattern, totals.clean_pattern, totals.load_failing },
    );
    return totals;
}

fn runCase(
    gpa: Allocator,
    io: Io,
    out: *Io.Writer,
    schema: *const pacer.Schema,
    harness_schema: anytype,
    root: []const u8,
    name: []const u8,
    totals: *Totals,
) !void {
    errdefer |err| out.print("parity: {s}: FAIL ({s})\n", .{ name, @errorName(err) }) catch {};

    // Runtime singleton: reset before EVERY case and after every exit path.
    // The initial call is idempotent; the deferred one covers assertions and
    // errors as well as ordinary completion.
    defer NativeRt.reset();
    NativeRt.reset();

    var arena = std.heap.ArenaAllocator.init(gpa);
    defer arena.deinit();
    const a = arena.allocator();

    const doc = try readCaseFile(a, io, out, root, name, "doc.sjon");
    const times = try readCaseFile(a, io, out, root, name, "times.sjon");
    const expected = try readCaseFile(a, io, out, root, name, "expected.sjon");

    const golden = parseInitialLoad(expected) catch |err| {
        try out.print("parity: {s}: malformed expected.sjon: {s}\n", .{ name, @errorName(err) });
        return error.MalformedGolden;
    };

    const harness = (try CorpusHarness.parse(a, gpa, harness_schema, out, name, times)) orelse
        return error.MalformedHarness;
    const host_targets = try CorpusHarness.targetsAs(pacer.Compile.Target, a, harness);

    // Stationary public Driver: initialized in its final storage, never moved
    // while the evaluator borrows the result.
    var driver: pacer.Driver = undefined;
    try driver.init(a, schema, doc, host_targets);
    defer driver.deinit();

    const compile_ok = driver.result.ok();
    const has_pattern = if (driver.result.table) |*table| blk: {
        for (table.tracks) |track| {
            if (track.source == .pattern) break :blk true;
        }
        break :blk false;
    } else false;

    const class = classify(golden.initial_ok, compile_ok, has_pattern) catch {
        try out.print(
            "parity: {s}: compile/golden disagreement: golden :ok {s}, actual :ok {s}, pattern tracks {s}\n",
            .{ name, if (golden.initial_ok) "true" else "false", if (compile_ok) "true" else "false", if (has_pattern) "true" else "false" },
        );
        return error.CompileGoldenDisagreement;
    };

    switch (class) {
        .load_failing => {
            // Diagnostic fixtures are refused BEFORE either asserted pack
            // API. No preflight, no encode, no PACB bytes.
            switch (try packCase(a, &driver.result, host_targets)) {
                .compile_refused => {},
                .preflight_refused => |diags| {
                    try out.print("parity: {s}: load-failing case reached preflight ({d} diagnostic(s))\n", .{ name, diags.len });
                    return error.LoadFailureReachedPack;
                },
                .encoded => |bytes| {
                    try out.print("parity: {s}: load-failing case produced {d} PACB byte(s)\n", .{ name, bytes.len });
                    return error.LoadFailureProducedPacb;
                },
            }
        },
        .clean_pattern => {
            // The class is known and explicitly reported; skips are not
            // passes. `preflight` must carry the existing refusal, and encode
            // must never run.
            switch (try packCase(a, &driver.result, host_targets)) {
                .preflight_refused => |diags| {
                    var refused_pattern = false;
                    for (diags) |d| {
                        if (d.code == .pack_patterns_unsupported) refused_pattern = true;
                    }
                    if (!refused_pattern) {
                        try out.print("parity: {s}: clean pattern case lacks pack_patterns_unsupported\n", .{name});
                        return error.PatternRefusalMissing;
                    }
                    try out.print("parity: {s}: skipped-pending-SJON (pattern tracks await the SJON owner decision)\n", .{name});
                },
                .encoded => |bytes| {
                    try out.print("parity: {s}: clean pattern case encoded {d} PACB byte(s)\n", .{ name, bytes.len });
                    return error.PatternEncoded;
                },
                .compile_refused => return error.PatternCompileRefusedAfterOk,
            }
        },
        .clean_non_pattern => {
            switch (try packCase(a, &driver.result, host_targets)) {
                .encoded => |pacb| {
                    try replayCase(a, out, name, &driver, harness, host_targets, pacb);
                },
                .compile_refused => return error.CompileRefusedAfterOk,
                .preflight_refused => |diags| {
                    try out.print("parity: {s}: unexplained non-pattern preflight refusal ({d} diagnostic(s))\n", .{ name, diags.len });
                    for (diags) |d| {
                        try out.print("  {s}: {s}\n", .{ @tagName(d.code), d.message });
                    }
                    return error.UnexplainedPreflightRefusal;
                },
            }
        },
    }

    // Count the case only after its whole class action succeeded. A skip is
    // counted separately and never as a pass.
    switch (class) {
        .clean_non_pattern => totals.clean_non_pattern += 1,
        .clean_pattern => totals.clean_pattern += 1,
        .load_failing => totals.load_failing += 1,
    }
}

/// Total classifier: golden outcome must agree with the actual compile; a
/// clean case is a pattern skip iff its compiled table carries a `.pattern`
/// source tag. No source substring, no case name.
pub fn classify(golden_ok: bool, compile_ok: bool, has_pattern: bool) ClassifyError!Class {
    if (golden_ok != compile_ok) return error.CompileGoldenDisagreement;
    if (!compile_ok) return .load_failing;
    return if (has_pattern) .clean_pattern else .clean_non_pattern;
}

/// Pack orchestration with separate compile and preflight refusal arms. A
/// dirty result NEVER reaches `PacbEncode.preflight`/`encode` (both assert
/// `result.ok()`); a pattern result may reach preflight but never encode.
pub fn packCase(
    a: Allocator,
    result: *const pacer.Compile.CompileResult,
    host_targets: []const pacer.Compile.Target,
) !Packed {
    if (!result.ok()) return .compile_refused;

    var diags: std.ArrayList(pacer.Compile.Diagnostic) = .empty;
    try pacer.PacbEncode.preflight(a, result, &diags);
    if (diags.items.len != 0) return .{ .preflight_refused = diags.items };

    const bytes = try pacer.PacbEncode.encode(a, result, host_targets);
    return .{ .encoded = bytes };
}

/// Replay one clean non-pattern case through the actual production loader.
fn replayCase(
    a: Allocator,
    out: *Io.Writer,
    name: []const u8,
    driver: *pacer.Driver,
    harness: Harness,
    host_targets: []const pacer.Compile.Target,
    pacb: []const u8,
) !void {
    // 1. Canonical 'PACT' of the ORIGINAL host join — never result.targets.
    const pact_buf = try a.alloc(u8, pacer.PactCodec.targetsEncodedLen(host_targets));
    const pact = try pacer.PactCodec.encodeTargets(host_targets, pact_buf);

    // 2. Caps BEFORE copy/narrow.
    const pacb_cap: usize = NativeRt.pacbCap();
    const targets_cap: usize = NativeRt.targetsCap();
    if (pacb.len > pacb_cap) {
        try out.print("parity: {s}: PACB length {d} exceeds runtime cap {d}\n", .{ name, pacb.len, pacb_cap });
        return error.PacbOverCap;
    }
    if (pact.len > targets_cap) {
        try out.print("parity: {s}: PACT length {d} exceeds runtime cap {d}\n", .{ name, pact.len, targets_cap });
        return error.PactOverCap;
    }

    // 3. Copy into the production zones, then load through the real export.
    @memcpy(NativeRt.pacbPtr()[0..pacb.len], pacb);
    @memcpy(NativeRt.targetsPtr()[0..pact.len], pact);
    const status = NativeRt.load(@intCast(pacb.len), @intCast(pact.len));
    if (status != 0) {
        try out.print(
            "parity: {s}: production load status {d} (reason {d}); expected 0\n",
            .{ name, status, NativeRt.loadError() },
        );
        return error.ProductionLoadRefused;
    }

    // 4. Complete metadata: fresh text encode == embedded PACM == runtime copy.
    const fresh_buf = try a.alloc(u8, pacer.Abi.metaEncodedLen(&driver.result));
    const fresh = try pacer.Abi.encodeMeta(&driver.result, fresh_buf);

    const directory = pacer.Pacb.parseDirectory(pacb, null) catch |err| {
        try out.print("parity: {s}: cannot parse own PACB directory: {s}\n", .{ name, @errorName(err) });
        return error.PacbDirectoryInvalid;
    };
    const pacm_section = directory.find(.pacm) orelse {
        try out.print("parity: {s}: encoded PACB has no PACM section\n", .{name});
        return error.MissingPacm;
    };
    const embedded = pacb[@as(usize, pacm_section.off)..][0..@as(usize, pacm_section.len)];

    try expectSameBytes(out, name, null, "meta fresh-vs-embedded", fresh, embedded);

    const got_meta_len: usize = NativeRt.metaLen();
    if (got_meta_len > embedded.len) {
        // The runtime served a length above its own embedded PACM bound.
        // Report the surface/lengths without reading past the cap.
        try out.print(
            "parity: {s}: step <meta>: meta embedded-vs-runtime MISMATCH: expected {d} byte(s), actual {d} byte(s); first difference not readable: runtime length exceeds embedded PACM (refusing to copy)\n",
            .{ name, embedded.len, got_meta_len },
        );
        return error.ParityMismatch;
    }
    const got_meta = try a.dupe(u8, NativeRt.metaPtr()[0..got_meta_len]);
    try expectSameBytes(out, name, null, "meta embedded-vs-runtime", embedded, got_meta);

    // 5. Replay every current script form in document order on BOTH paths.
    const evaluator = &driver.evaluator.?;

    for (harness.steps, 0..) |step, index| switch (step) {
        .eval => |bits| {
            const seconds: f64 = @bitCast(bits);
            if (evaluator.evalSeconds(seconds)) |entries| {
                // A valid empty frame still encodes as a 12-byte header.
                var want_buf: [MAX_WRITES]u8 = undefined;
                const want = pacer.Writes.encode(entries, &want_buf) catch
                    return error.TextFrameEncodeFailed;

                const got_len: usize = NativeRt.evalSeconds(seconds);
                if (got_len > MAX_WRITES) {
                    try out.print(
                        "parity: {s}: step {d}: writes MISMATCH: expected {d} byte(s), actual {d} byte(s); first difference not readable: runtime length exceeds writes capacity {d}\n",
                        .{ name, index, want.len, got_len, MAX_WRITES },
                    );
                    return error.ParityMismatch;
                }
                const got = try a.dupe(u8, NativeRt.writesPtr()[0..got_len]);
                try expectSameBytes(out, name, index, "writes", want, got);
            } else |_| {
                // Text path: out-of-range host clock. Production returns 0,
                // which is distinct from an encoded empty frame (12 bytes).
                const got_len = NativeRt.evalSeconds(seconds);
                if (got_len != 0) {
                    try out.print(
                        "parity: {s}: step {d}: eval out-of-range mismatch: expected 0 bytes, actual {d} bytes\n",
                        .{ name, index, got_len },
                    );
                    return error.ParityMismatch;
                }
            }
        },
        .set_control => |sc| {
            const value: [4]f32 = .{
                @bitCast(sc.bits[0]), @bitCast(sc.bits[1]), @bitCast(sc.bits[2]), @bitCast(sc.bits[3]),
            };
            // Production returns 0 on acceptance, 1 on rejection (the
            // T1 facade contract); normalize the text bool the same way.
            const want: u32 = if (evaluator.setControl(@intCast(sc.index), value)) 0 else 1;
            const got = NativeRt.setControl(sc.index, value[0], value[1], value[2], value[3]);
            try expectScalar(out, name, index, "set-control", want, got);
        },
        .clear_control => |control_index| {
            const want: u32 = if (evaluator.clearControl(@intCast(control_index))) 0 else 1;
            const got = NativeRt.clearControl(control_index);
            try expectScalar(out, name, index, "clear-control", want, got);
        },
        .set_bpm => |bits| {
            const bpm: f64 = @bitCast(bits);
            const want: u32 = if (evaluator.setBpm(bpm)) 0 else 1;
            const got = NativeRt.setBpm(bpm);
            try expectScalar(out, name, index, "set-bpm", want, got);
        },
        .register_control => |rc| {
            // Normalize the two existing sentinel representations: text null
            // and production 0xffff_ffff both mean "no slot".
            const want: u32 = if (evaluator.registerControl(rc.target_id, rc.registry, rc.ncomp)) |slot|
                @intCast(slot)
            else
                NO_SLOT;
            const got = NativeRt.registerControl(rc.target_id, rc.registry, rc.ncomp);
            try expectScalar(out, name, index, "register-control", want, got);
        },
    };

    // 6. Failure counters after the SAME sequence.
    const want_failures: u32 = @truncate(evaluator.expr_failures);
    const got_failures = NativeRt.exprFailures();
    try expectScalar(out, name, harness.steps.len, "expr-failures", want_failures, got_failures);
}

/// Compare complete byte surfaces. The report names the case, script step,
/// surface, both lengths, and the first differing offset with both bytes (or
/// end-of-buffer) — including a length-only mismatch.
pub fn expectSameBytes(
    out: *Io.Writer,
    name: []const u8,
    step: ?usize,
    surface: []const u8,
    want: []const u8,
    got: []const u8,
) !void {
    if (std.mem.eql(u8, want, got)) return;

    try out.print("parity: {s}: step ", .{name});
    if (step) |index| {
        try out.print("{d}", .{index});
    } else {
        try out.print("<meta>", .{});
    }
    try out.print(": {s} MISMATCH: expected {d} byte(s), actual {d} byte(s); ", .{ surface, want.len, got.len });

    const offset = firstDifference(want, got) orelse unreachable; // unequal slices
    if (offset < want.len and offset < got.len) {
        try out.print("first difference at offset {d}: expected 0x{X:0>2}, actual 0x{X:0>2}\n", .{
            offset, want[offset], got[offset],
        });
    } else if (offset < want.len) {
        try out.print("first difference at offset {d}: expected 0x{X:0>2}, actual end-of-buffer\n", .{
            offset, want[offset],
        });
    } else {
        try out.print("first difference at offset {d}: expected end-of-buffer, actual 0x{X:0>2}\n", .{
            offset, got[offset],
        });
    }
    return error.ParityMismatch;
}

pub fn firstDifference(want: []const u8, got: []const u8) ?usize {
    const common = @min(want.len, got.len);
    for (0..common) |i| {
        if (want[i] != got[i]) return i;
    }
    return if (want.len == got.len) null else common;
}

fn expectScalar(
    out: *Io.Writer,
    name: []const u8,
    step: usize,
    surface: []const u8,
    want: u32,
    got: u32,
) !void {
    if (want == got) return;
    try out.print(
        "parity: {s}: step {d}: {s} MISMATCH: expected {d}, actual {d}\n",
        .{ name, step, surface, want, got },
    );
    return error.ParityMismatch;
}

/// Parse ONLY the initial golden load record. The first non-comment line
/// after the generated header must be `(load :ok true|false)`. A second load
/// before any other top-level record is a duplicate initial record; a load
/// after another record is a later reload and is ignored for classification.
/// Unknown top-level heads are malformed for this classifier.
pub fn parseInitialLoad(expected: []const u8) GoldenError!Golden {
    var lines = std.mem.splitScalar(u8, expected, '\n');

    const header = lines.next() orelse return error.MalformedHeader;
    if (!std.mem.eql(u8, std.mem.trimEnd(u8, header, " \t\r"), GENERATED_HEADER))
        return error.MalformedHeader;

    var initial: ?bool = null;
    var seen_other_form = false;

    while (lines.next()) |raw| {
        const line = std.mem.trimEnd(u8, raw, " \t\r");
        if (line.len == 0) continue;
        // Nested forms are indented; a standalone close belongs to the
        // preceding top-level record. Neither is a new record.
        if (line[0] == ' ' or line[0] == '\t') continue;
        if (line[0] == ';') continue;
        if (line[0] == ')') continue;
        if (line[0] != '(') {
            if (initial == null) return error.MissingInitialLoad;
            return error.MalformedGolden;
        }

        const head = topLevelHead(line) orelse return error.MalformedGolden;
        if (std.mem.eql(u8, head, "load")) {
            const ok = parseLoadRecord(line) orelse return error.MalformedLoadRecord;
            if (initial == null) {
                initial = ok;
                continue;
            }
            if (!seen_other_form) return error.DuplicateInitialLoad;
            // Later reload record: a different surface, not a classification.
            continue;
        }

        if (initial == null) return error.MissingInitialLoad;
        if (!knownTopLevelForm(head)) return error.UnknownTopLevelForm;
        seen_other_form = true;
    }

    return .{ .initial_ok = initial orelse return error.MissingInitialLoad };
}

fn parseLoadRecord(line: []const u8) ?bool {
    if (std.mem.eql(u8, line, "(load :ok true)")) return true;
    if (std.mem.eql(u8, line, "(load :ok false)")) return false;
    return null;
}

fn topLevelHead(line: []const u8) ?[]const u8 {
    if (line.len < 2 or line[0] != '(') return null;
    var end: usize = 1;
    while (end < line.len and line[end] != ' ' and line[end] != '\t' and line[end] != ')') : (end += 1) {}
    if (end == 1) return null;
    return line[1..end];
}

fn knownTopLevelForm(head: []const u8) bool {
    // Current golden records plus the T5 lifecycle forms, so a later reload
    // record never reads as an unknown form while the initial record stays
    // the only classification input.
    const heads = [_][]const u8{
        "diag",             "meta",          "eval",
        "set-control",      "clear-control", "set-bpm",
        "register-control", "reload",        "registry-mismatch",
    };
    for (heads) |known| {
        if (std.mem.eql(u8, head, known)) return true;
    }
    return false;
}

fn readCaseFile(
    a: Allocator,
    io: Io,
    out: *Io.Writer,
    root: []const u8,
    name: []const u8,
    file: []const u8,
) ![:0]u8 {
    const path = std.fs.path.join(a, &.{ root, name, file }) catch |err| {
        try out.print("parity: {s}: cannot join path for {s}: {s}\n", .{ name, file, @errorName(err) });
        return error.CaseFileUnavailable;
    };
    return Io.Dir.cwd().readFileAllocOptions(io, path, a, .limited(MAX_FILE_BYTES), .of(u8), 0) catch |err| {
        try out.print("parity: {s}: cannot read {s}: {s}\n", .{ name, file, @errorName(err) });
        return error.CaseFileUnavailable;
    };
}
