#!/bin/sh
# Render docs/score-language.md from schema/pacer.sjon.
#
# The manifest already carries a `:description` on every form, key and value
# kind — that prose is the score language's documentation, and this makes it
# a page instead of leaving it readable only by a validator. One source, so
# the reference cannot drift from the rules.
#
#   tools/score_docs.sh <path-to-sjon-cli> [--update]
#
# Default mode CHECKS: it re-renders to a temp file and diffs against the
# committed page, failing if they differ (this is the leg `zig build verify`
# depends on). `--update` writes the page instead. Both go through the same
# render, so the gate compares what the verb would produce.
set -eu

SJON="${1:?usage: score_docs.sh <sjon-cli> [--update]}"
MODE="${2:-check}"
MANIFEST="schema/pacer.sjon"
PAGE="docs/score-language.md"

HEADER='<!-- GENERATED by `zig build score-docs` from schema/pacer.sjon — do not hand-edit. -->'

tmp_out=$(mktemp)
tmp_err=$(mktemp)
tmp_dir=$(mktemp -d)
trap 'rm -rf "$tmp_out" "$tmp_err" "$tmp_dir"' EXIT

# Render into a directory of its own rather than through `--output=-`: the
# CLI's stdout writer is positional, so anything already written to a
# redirected stdout (the header line, say) is overwritten from offset 0. The
# exporter also narrates its lossy JSON-Schema mappings on stderr (all
# `[info …]`) — kept for a failure, swallowed otherwise so a clean `verify`
# stays quiet.
if ! "$SJON" export-schema "$MANIFEST" --target=markdown --output="$tmp_dir" 2>"$tmp_err"; then
    echo "score-docs: export-schema failed:" >&2
    cat "$tmp_err" >&2
    exit 1
fi

set -- "$tmp_dir"/*.md
if [ "$#" -ne 1 ] || [ ! -f "$1" ]; then
    echo "score-docs: expected exactly one rendered page, got $#" >&2
    exit 1
fi

{
    printf '%s\n\n' "$HEADER"
    cat "$1"
} >"$tmp_out"

if [ "$MODE" = "--update" ]; then
    cp "$tmp_out" "$PAGE"
    echo "score-docs: wrote $PAGE"
    exit 0
fi

if ! diff -u "$PAGE" "$tmp_out"; then
    echo "score-docs: $PAGE is stale — \`zig build score-docs\` regenerates it" >&2
    exit 1
fi
echo "score-docs: $PAGE is current"
